"""Reproducible *independent reference-trace* audit for NC15 inward carries.

Not a proof of automatic future border/width selection: both reference border
traces and widths are generated by literal arithmetic for the audit only.
The mod-99 series, however, is powered from the initial residue and widths,
not copied from the reference integers.
"""

from __future__ import annotations

import json
from itertools import accumulate, zip_longest

from number_compiler.sequences.double_reverse.temporal_inward_constraints import (
    InwardCarryConstraints,
)


def trajectory(seed: int, horizon: int) -> tuple[int, ...]:
    output = [seed]
    for _ in range(horizon):
        value = output[-1]
        reversed_value = 0
        while value:
            value, digit = divmod(value, 10)
            reversed_value = 10 * reversed_value + digit
        output.append(2 * reversed_value)
    return tuple(output)


def compare(
    seed: int, horizon: int = 24, exposed_each_side: int = 2
) -> dict[str, object]:
    reference = trajectory(seed, horizon)
    strings = [str(number) for number in reference]
    widths = tuple(map(len, strings))
    residues = [seed % 99]
    for width in widths[:-1]:
        residues.append(2 * pow(10, width - 1, 99) * residues[-1] % 99)
    assert all(r == x % 99 for r, x in zip(residues, reference, strict=True))

    def input_grammar() -> InwardCarryConstraints:
        grammar = InwardCarryConstraints(widths)
        for time, digits in enumerate(strings):
            # Only two edges, NOT the interior, are supplied by the oracle.
            grammar.constrain_prefix(time, digits[:exposed_each_side])
            grammar.constrain_suffix(time, digits[-exposed_each_side:])
            grammar.constrain_residue(time, 99, residues[time])
        return grammar

    forward, joint = input_grammar(), input_grammar()
    f, b = forward.propagate(direction="forward"), joint.propagate(direction="both")
    newly_narrowed: list[tuple[int, int]] = []
    newly_forced: list[tuple[int, int, int]] = []
    for t, digits in enumerate(strings):
        actual_digits = tuple(map(int, digits))
        actual_cells = tuple(enumerate(actual_digits))
        assert all(digit in joint.digits(t, i) for i, digit in actual_cells)
        assert all(int(digit >= 5) in joint.carry(t, i) for i, digit in actual_cells)
        for i, _digit in actual_cells:
            if len(joint.digits(t, i)) < len(forward.digits(t, i)):
                newly_narrowed.append((t, i))
            if len(joint.digits(t, i)) == 1 and len(forward.digits(t, i)) != 1:
                newly_forced.append((t, i, joint.digits(t, i)[0]))
        if t < horizon:
            nxt = strings[t + 1]
            borrow_chain = accumulate(
                zip_longest(nxt, digits, fillvalue="0"),
                lambda borrow, pair: int(int(pair[0]) < int(pair[1]) + borrow),
                initial=0,
            )
            expected_borrows = tuple(borrow_chain)[1:]
            assert all(
                borrow in joint.borrow(t, position)
                for position, borrow in enumerate(expected_borrows, start=1)
            )
    return {
        "seed": str(seed),
        "generation_interval": [73, 73 + horizon]
        if seed == 17781675275941694822050964043040742
        else None,
        "horizon": horizon,
        "start_width": widths[0],
        "end_width": widths[-1],
        "observed_prefix_suffix_digits_per_side": exposed_each_side,
        "residue_authority": "mod-99 recurrence from widths and initial residue",
        "border_width_authority": "independently iterated reference trajectory, NOT a produced macro",
        "forward_known_digit_cells": sum(f.known_digit_counts),
        "bidirectional_known_digit_cells": sum(b.known_digit_counts),
        "extra_exact_digit_cells": len(newly_forced),
        "narrowed_digit_domains": len(newly_narrowed),
        "forward_forced_carries": sum(f.forced_carry_counts),
        "bidirectional_forced_carries": sum(b.forced_carry_counts),
        "forward_forced_raw_borrows": sum(
            v != 2 for row in f.raw_reverse_borrow_vectors for v in row
        ),
        "bidirectional_forced_raw_borrows": sum(
            v != 2 for row in b.raw_reverse_borrow_vectors for v in row
        ),
        "forward_forced_pair_bands": sum(
            len(bands) == 1 for row in f.pair_domains for bands in row
        ),
        "bidirectional_forced_pair_bands": sum(
            len(bands) == 1 for row in b.pair_domains for bands in row
        ),
        "extra_exact_digit_examples": newly_forced[:20],
        "first_unknown_interior_high": list(joint.digits(0, exposed_each_side)),
        "first_unknown_interior_low": list(
            joint.digits(0, len(strings[0]) - exposed_each_side - 1)
        ),
        "fixed_point_rounds": b.rounds,
        "full_integer_reconstruction": all(
            count == 0 for count in b.conditional_digit_counts
        ),
    }


def main() -> int:
    full = compare(17781675275941694822050964043040742)
    small = compare(173488, 12)
    result = {"user_trajectory": full, "certified_cylinder_entry_reference": small}
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    from devtools.runs import run_reported

    raise SystemExit(run_reported(main))
