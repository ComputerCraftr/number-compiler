def fast_multipoint_bend_audit(
    family: str,
    parameter: int,
    *,
    start: int,
    span: int,
    locate_first_bend: bool = False,
    extract_proper_factor: bool = True,
    include_direct_control: bool = True,
) -> FastMultipointBendAudit:
    """Evaluate all baby blocks simultaneously with exact composite-ring MPE.

    The final support decision is one GCD.  A caller that only needs the
    prime/composite sheet therefore pays no factor-location work.  If a local
    bend/factor witness is requested, a product tree over the already-computed
    baby-block values finds the first supported block in O(log span) GCDs; an
    optional second tree descends inside that one baby block.
    """
    spec, start, span = bounded_jet_spec(family, parameter, start, span)
    b = max(1, isqrt(span))
    if b * b < span:
        b += 1
    full = span // b
    tail = span - full * b
    counter = _PolyCounter()
    arena = ProgressionProductArena()
    baby_morphism = ProgressionProductMorphism(spec.modulus, 0, -1, b)
    qpoly = _progression_product_polynomial(
        baby_morphism,
        spec.modulus,
        counter,
        arena,
    )
    inv_c = pow(spec.stride, -1, spec.modulus)
    giant_morphism = ProgressionProductMorphism(
        spec.modulus,
        inv_c + start,
        b,
        full,
    )
    values = _multipoint_evaluate_progression_monic_tree(
        qpoly,
        giant_morphism,
        spec.modulus,
        counter,
        arena,
    )
    tail_start = start + full * b
    tail_values = tuple(
        _normalized_slot_value(spec, tail_start + offset, inv_c)
        for offset in range(tail)
    )
    support_leaves = tuple(values) + tail_values
    support_tree, support_tree_mults = support_product_tree(
        support_leaves, spec.modulus
    )
    normalized_product = support_tree.product
    combines = support_tree_mults
    # Tail atoms are already leaves in the support product tree, so there is no
    # separate tail multiplication pass anymore.
    tail_mults = 0
    scale_mults = binary_power_composition_count(span) + 1
    reconstructed = (
        normalized_product * pow(spec.stride, span, spec.modulus) % spec.modulus
    )
    support = gcd(spec.modulus, reconstructed)
    final_gcds = 1
    split_gcds = 0
    first_factor = None
    first_bend_slot = None
    first_bend_gcd = 1
    block_locator_gcds = 0
    leaf_locator_gcds = 0

    # Digit/theorem consumers need only know whether support is nonunit.  Do
    # not extract a factor unless FULL support needs a proper packet or the
    # caller explicitly requests the first bend coordinate.
    need_locator = (support == spec.modulus and bool(extract_proper_factor)) or (
        support > 1 and bool(locate_first_bend)
    )
    if need_locator:

        def atom_support(block_start: int) -> tuple[int, int, int]:
            atom_values = tuple(
                _normalized_slot_value(spec, block_start + offset, inv_c)
                for offset in range(b)
            )
            atom_tree, _atom_mults = support_product_tree(atom_values, spec.modulus)
            return first_supported_leaf(
                atom_tree,
                spec.modulus,
                prefix_values=atom_values,
                prefix_limit=4,
            )

        leaf_index, leaf_support, calls = first_supported_leaf(
            support_tree,
            spec.modulus,
            prefix_values=support_leaves,
            prefix_limit=1,
        )
        block_locator_gcds += calls
        if support == spec.modulus and extract_proper_factor:
            split_gcds += calls
        if leaf_index < full:
            block_start = start + leaf_index * b
            if support == spec.modulus and extract_proper_factor:
                # The first supported baby block is already a proper support
                # packet unless all components collide inside that one block.
                if 1 < leaf_support < spec.modulus:
                    first_factor = leaf_support
                else:
                    atom_index, atom_factor, atom_calls = atom_support(block_start)
                    split_gcds += atom_calls
                    first_factor = atom_factor
                    if locate_first_bend:
                        first_bend_slot = block_start + atom_index
                        first_bend_gcd = atom_factor
                        leaf_locator_gcds += atom_calls
            if locate_first_bend and first_bend_slot is None:
                atom_index, atom_factor, atom_calls = atom_support(block_start)
                first_bend_slot = block_start + atom_index
                first_bend_gcd = atom_factor
                leaf_locator_gcds += atom_calls
        else:
            # Tail leaves represent one original slot each.
            tail_offset = leaf_index - full
            first_bend_slot = tail_start + tail_offset
            first_bend_gcd = leaf_support
            if support == spec.modulus and extract_proper_factor:
                first_factor = leaf_support

    if 1 < support < spec.modulus:
        first_factor = support
    if support == spec.modulus and extract_proper_factor and first_factor is None:
        raise AssertionError("FULL support failed logarithmic product-tree descent")
    # The linear direct interval is a bounded differential, not part of the
    # BSGS algorithm.  Production-like/support-only callers must not replay it
    # after doing the sublinear multipoint work.
    direct = (
        build_special_jet_interval(spec, start, span)
        if include_direct_control
        else None
    )
    direct_product = reconstructed if direct is None else direct.product
    direct_support = support if direct is None else direct.support_gcd
    direct_multiplications = (
        max(0, span - 1) if direct is None else direct.multiplications
    )
    charged = counter.scalar_multiplications + combines + tail_mults + scale_mults
    total_ring_ops = charged + counter.coefficient_additions
    baby_tree_storage = _linear_product_tree_storage_entries(b)
    point_tree_storage = _linear_product_tree_storage_entries(full)
    # The implementation retains the complete point subproduct tree while
    # descending remainders.  Charge that O(sqrt(l) log l) storage honestly;
    # current remainder layers add only O(sqrt(l)) coefficient slots.
    tree_storage = max(baby_tree_storage, point_tree_storage)
    remainder_layer_upper = 2 * (b + full + 1)
    structural_entries = (
        max(
            baby_tree_storage,
            point_tree_storage + len(qpoly) + remainder_layer_upper,
        )
        + tail
    )
    exponent = log2(3.0) / 2.0
    return FastMultipointBendAudit(
        spec.family,
        spec.parameter,
        start,
        span,
        spec.modulus,
        b,
        full,
        tail,
        values,
        reconstructed,
        direct_product,
        reconstructed == direct_product,
        support,
        direct_support,
        bool(include_direct_control),
        first_factor,
        counter.scalar_multiplications,
        counter.coefficient_additions,
        counter.polynomial_multiplications,
        counter.newton_iterations,
        counter.remainder_calls,
        combines,
        tail_mults,
        scale_mults,
        final_gcds,
        split_gcds,
        first_bend_slot,
        first_bend_gcd,
        block_locator_gcds,
        leaf_locator_gcds,
        support_tree_mults,
        charged,
        counter.coefficient_additions,
        total_ring_ops,
        direct_multiplications,
        max(b, full),
        tree_storage,
        structural_entries,
        structural_entries < span,
        True,
        charged < direct_multiplications,
        total_ring_ops < direct_multiplications,
        exponent,
        exponent < 1.0,
        False,
        True,
        baby_morphism.description_bits,
        giant_morphism.description_bits,
        arena.hits,
        arena.misses,
        arena.materialized_coefficient_slots,
        arena.raw_state_count,
        arena.algebraic_shape_count,
        arena.algebraic_compression_ratio,
        arena.shape_hits,
        arena.shape_misses,
        False,
        True,
    )


def fast_multipoint_support_decision(
    family: str,
    parameter: int,
    *,
    start: int,
    span: int,
) -> FastMultipointBendAudit:
    """Output-relative bend decision with no proper-factor localization.

    A digit/theorem branch only needs CLEAR versus NONUNIT.  In particular a
    FULL support gcd already proves that the finite candidate window contains
    nonunit support; extracting a proper divisor is optional witness work and
    is not charged to this observer.
    """
    return fast_multipoint_bend_audit(
        family,
        parameter,
        start=start,
        span=span,
        locate_first_bend=False,
        extract_proper_factor=False,
        include_direct_control=False,
    )


