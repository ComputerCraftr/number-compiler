def residue_refined_bend_audit(family: str, parameter: int) -> ResidueRefinedBendAudit:
    spec, singular = required_singularity(family, parameter)
    q = singular.denominator_gcd
    bad = singular.first_slot
    if bad is None:
        raise ValueError("required singularity has no first slot")
    regular = next(
        m for m in range(1, spec.max_slot + 1) if m != bad and spec.slot_value(m) % q
    )

    def residues(slot: int) -> tuple[tuple[int, int], int]:
        pair = (1 % q, (spec.stride * slot) % q)
        return pair, sum(pair) % q

    rr, rsum = residues(regular)
    sr, ssum = residues(bad)
    rg = gcd(spec.modulus, spec.slot_value(regular))
    sg = gcd(spec.modulus, spec.slot_value(bad))
    return ResidueRefinedBendAudit(
        spec.family,
        spec.parameter,
        spec.modulus,
        q,
        regular,
        bad,
        rr,
        sr,
        rsum,
        ssum,
        True,
        True,
        rsum == 0,
        ssum == 0,
        rg,
        sg,
        rg == 1 and sg > 1,
        True,
    )


