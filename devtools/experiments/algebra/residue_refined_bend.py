def _horner_mod(
    coefficients: tuple[int, int, int, int, int, int, int]
    | tuple[int, int, int, int, int, int, int, int]
    | tuple[int, int, int, int, int, int, int, int, int],
    point: int,
    modulus: int,
) -> int:
    out = 0
    for coefficient in reversed(tuple(coefficients)):
        out = (out * int(point) + int(coefficient)) % int(modulus)
    return out


def multipoint_engine_audit() -> MultipointEngineAudit:
    """Differential-check the fast remainder tree over several composite rings."""
    rows: list[MultipointEngineCase] = []
    cases = (
        (45, (7, 11, 5, 19, 3, 8, 1), (1, 2, 4, 7, 11)),
        (65, (3, 17, 9, 4, 12, 6, 2, 1), (0, 3, 8, 14, 21, 34)),
        (91, (5, 0, 12, 7, 2, 15, 4, 1), (2, 5, 9, 16, 27)),
        (221, (13, 4, 0, 8, 17, 3, 9, 2, 1), (1, 6, 12, 19, 31, 44)),
    )
    for modulus, polynomial, points in cases:
        counter = _PolyCounter()
        actual = _multipoint_evaluate_monic_tree(
            tuple(v % modulus for v in polynomial),
            tuple(points),
            modulus,
            counter,
        )
        expected = tuple(_horner_mod(polynomial, x, modulus) for x in points)
        rows.append(
            MultipointEngineCase(
                modulus,
                len(polynomial) - 1,
                len(points),
                expected,
                actual,
                expected == actual,
                counter.scalar_multiplications,
                counter.coefficient_additions,
            )
        )
    return MultipointEngineAudit(
        tuple(rows),
        all(row.exact for row in rows),
        all(
            any(modulus % q == 0 for q in range(2, isqrt(modulus) + 1))
            for modulus, *_ in cases
        ),
        True,
    )


