"""Residue-refined tropical bend/Fitting research for special-number ghosts.

The v0.52.4 tropical pass isolated the source event at one admissible slot

    x_m = 1 + C*m

as strict nonarchimedean excess: the two summands have equal local valuation
zero, while their leading residues may cancel on a hidden prime axis q|N.
There is an important simplification at a *single* slot: factor-free bend
membership is already exactly

    gcd(N, x_m) > 1.

Thus the unresolved problem is not a new pointwise phase oracle.  It is batched
bend-locus evaluation over a huge interval without visiting every m.

This module gives that interval a module-theoretic form.  For

    M[a,l] = direct_sum_m R/(x_m),   R = Z/NZ,

its zeroth Fitting ideal is generated by the interval product.  Its support is
therefore exactly the arithmetic ghost/bend support.  The annihilator gives the
same prime support through the lcm of the pointwise gcd divisors.  These facts
explain why previous product/divisor formulations were equivalent.

The new computational experiment uses a Strassen-style baby/giant split.  A
single degree-b rising-factorial polynomial is built, then all full block
values are obtained simultaneously by a monic subproduct/remainder tree.  The
polynomial arithmetic uses exact Karatsuba convolution and Newton inversion of
reversed monic divisors, so no field division or hidden prime factor is used.
Over Z/NZ this remains valid because every divisor polynomial is monic.

With b ~= sqrt(l), the evaluated state has O(sqrt(l)) degree/points.  Under
Karatsuba coefficient multiplication M(d)=O(d^log_2(3)), product/remainder
levels use O(M(sqrt(l)) log l) coefficient multiplications, giving a genuine
sublinear-in-l research evaluator (roughly l^0.7925 polylog l) rather than the
linear leaf scan.  This still is *not* polylogarithmic in l and therefore does
not close the release theorem.

Everything here is research-only.  Production must not import this module or
promote its sublinear factor-window evaluator as the missing logarithmic
Fermat/Mersenne source theorem.
"""

