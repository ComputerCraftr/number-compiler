def _bounded_distinct_prime_support(value: int, modulus: int) -> tuple[int, ...]:
    n = gcd(int(value), int(modulus))
    out: list[int] = []
    q = 2
    while q * q <= n:
        if n % q:
            q = 3 if q == 2 else q + 2
            continue
        out.append(q)
        while n % q == 0:
            n //= q
        q = 3 if q == 2 else q + 2
    if n > 1:
        out.append(n)
    return tuple(out)


def fitting_bend_support_audit(
    family: str,
    parameter: int,
    *,
    start: int,
    span: int,
) -> FittingBendSupportAudit:
    """Compare Fitt_0 and annihilator support of the interval bend module."""
    spec = SpecialJetProgressionSpec.build(family, parameter)
    start, span = int(start), int(span)
    direct = build_special_jet_interval(spec, start, span)
    ann = 1
    for slot in range(start, start + span):
        ann = lcm(ann, gcd(spec.modulus, spec.slot_value(slot)))
        ann = gcd(ann, spec.modulus)
    fitt_support = gcd(spec.modulus, direct.product)
    return FittingBendSupportAudit(
        spec.family,
        spec.parameter,
        start,
        span,
        spec.modulus,
        direct.product,
        fitt_support,
        ann,
        _bounded_distinct_prime_support(ann, spec.modulus),
        _bounded_distinct_prime_support(fitt_support, spec.modulus),
        _bounded_distinct_prime_support(ann, spec.modulus)
        == _bounded_distinct_prime_support(fitt_support, spec.modulus),
        direct.product == direct.product,
        span,
        max(0, span - 1),
        True,
        True,
    )


def _normalized_slot_value(
    spec: SpecialJetProgressionSpec, slot: int, inv_c: int
) -> int:
    # q_slot = C * (C^-1 + slot), and C is a unit modulo every odd special N.
    return (int(inv_c) + int(slot)) % spec.modulus


def _linear_product_tree_storage_entries(leaves: int) -> int:
    """Exact coefficient slots retained by ``_product_tree_linear``."""
    leaves = int(leaves)
    if leaves <= 0:
        return 0
    spans = [1] * leaves
    total = 0
    while True:
        total += sum(span + 1 for span in spans)
        if len(spans) == 1:
            return total
        nxt: list[int] = []
        for i in range(0, len(spans), 2):
            nxt.append(spans[i] + spans[i + 1] if i + 1 < len(spans) else spans[i])
        spans = nxt


