@dataclass(slots=True)
class _PolyCounter:
    scalar_multiplications: int = 0
    coefficient_additions: int = 0
    polynomial_multiplications: int = 0
    newton_iterations: int = 0
    remainder_calls: int = 0

    def add_product(self, muls: int, adds: int) -> None:
        self.scalar_multiplications += int(muls)
        self.coefficient_additions += int(adds)
        self.polynomial_multiplications += 1


def _trim_mod(values: Sequence[int], modulus: int) -> tuple[int, ...]:
    vals = [int(v) % modulus for v in values] or [0]
    while len(vals) > 1 and vals[-1] == 0:
        vals.pop()
    return tuple(vals)


def _poly_mul_mod(
    left: Sequence[int],
    right: Sequence[int],
    modulus: int,
    counter: _PolyCounter,
) -> tuple[int, ...]:
    a, b = _trim_mod(left, modulus), _trim_mod(right, modulus)
    raw, metrics = karatsuba_convolution(a, b, threshold=8)
    counter.add_product(metrics.scalar_multiplications, metrics.coefficient_additions)
    return _trim_mod(raw, modulus)


def _poly_sub_mod(
    left: tuple[int, ...], right: tuple[int, ...], modulus: int, counter: _PolyCounter
) -> tuple[int, ...]:
    n = max(len(left), len(right))
    out = [0] * n
    for i in range(n):
        a = left[i] if i < len(left) else 0
        b = right[i] if i < len(right) else 0
        out[i] = (int(a) - int(b)) % modulus
        counter.coefficient_additions += int(i < len(left) and i < len(right))
    return _trim_mod(out, modulus)


def _poly_reverse(
    values: tuple[int, ...], length: int | None = None
) -> tuple[int, ...]:
    vals = tuple(values)
    if length is not None:
        if len(vals) < length:
            vals = vals + (0,) * (length - len(vals))
        else:
            vals = vals[:length]
    return tuple(reversed(vals))


def _series_inverse_unit_constant(
    series: tuple[int, ...],
    length: int,
    modulus: int,
    counter: _PolyCounter,
) -> tuple[int, ...]:
    """Inverse ``series`` modulo X**length when series[0] == 1.

    Newton: g <- g * (2 - f*g).  This is division-free over Z/NZ.
    """
    length = int(length)
    if length < 1:
        return ()
    f = tuple(int(v) % modulus for v in series)
    if not f or f[0] % modulus != 1:
        raise ValueError("unit-constant series required")
    g: tuple[int, ...] = (1,)
    schedule = NewtonPrecisionMorphism(1)
    while schedule.precision < length:
        schedule = schedule.doubled(limit=length)
        width = schedule.precision
        fpart = f[:width] + (0,) * max(0, width - len(f))
        fg = _poly_mul_mod(fpart, g, modulus, counter)[:width]
        correction = [0] * width
        for i in range(width):
            value = fg[i] if i < len(fg) else 0
            correction[i] = ((2 if i == 0 else 0) - value) % modulus
            counter.coefficient_additions += 1
        g = _poly_mul_mod(g, correction, modulus, counter)[:width]
        g = tuple(v % modulus for v in g) + (0,) * max(0, width - len(g))
        counter.newton_iterations += 1
    return tuple(g[:length])


def _fast_remainder_monic(
    numerator: Sequence[int],
    divisor: tuple[int, ...],
    modulus: int,
    counter: _PolyCounter,
) -> tuple[int, ...]:
    """Remainder modulo a monic polynomial using reversed-series division."""
    a = _trim_mod(numerator, modulus)
    b = _trim_mod(divisor, modulus)
    if len(b) <= 1 or b[-1] != 1:
        raise ValueError("nonconstant monic divisor required")
    counter.remainder_calls += 1
    if len(a) < len(b):
        return a
    n, m = len(a) - 1, len(b) - 1
    q_len = n - m + 1
    a_rev = _poly_reverse(a, n + 1)[:q_len]
    b_rev = _poly_reverse(b, m + 1)
    inv = _series_inverse_unit_constant(b_rev, q_len, modulus, counter)
    q_rev = _poly_mul_mod(a_rev, inv, modulus, counter)[:q_len]
    q = _poly_reverse(q_rev, q_len)
    qb = _poly_mul_mod(q, b, modulus, counter)
    r = _poly_sub_mod(a, qb, modulus, counter)
    if len(r) > m:
        # The reversed quotient formula should already make these coefficients
        # zero; keep this assertion explicit so composite-ring arithmetic cannot
        # silently turn into an invalid field-only division.
        if any(r[m:]):
            raise AssertionError((a, b, q, r, modulus))
        r = r[:m]
    return _trim_mod(r, modulus)


def _product_tree_linear(
    roots: tuple[int, ...],
    modulus: int,
    counter: _PolyCounter,
) -> list[list[tuple[int, ...]]]:
    level: list[tuple[int, ...]] = [((-int(root)) % modulus, 1) for root in roots]
    if not level:
        return []
    levels = [level]
    while len(level) > 1:
        nxt: list[tuple[int, ...]] = []
        for i in range(0, len(level), 2):
            if i + 1 == len(level):
                nxt.append(level[i])
            else:
                nxt.append(_poly_mul_mod(level[i], level[i + 1], modulus, counter))
        level = nxt
        levels.append(level)
    return levels


def _multipoint_evaluate_monic_tree(
    polynomial: Sequence[int],
    roots: tuple[int, ...],
    modulus: int,
    counter: _PolyCounter,
) -> tuple[int, ...]:
    """Evaluate at all roots via a monic subproduct/remainder tree."""
    if not roots:
        return ()
    tree = _product_tree_linear(roots, modulus, counter)
    root_poly = tree[-1][0]
    current = [_fast_remainder_monic(polynomial, root_poly, modulus, counter)]
    for depth in range(len(tree) - 2, -1, -1):
        children = tree[depth]
        nxt: list[tuple[int, ...]] = []
        parent_index = 0
        child_index = 0
        while child_index < len(children):
            parent_rem = current[parent_index]
            left = children[child_index]
            nxt.append(_fast_remainder_monic(parent_rem, left, modulus, counter))
            child_index += 1
            if child_index < len(children):
                right = children[child_index]
                nxt.append(_fast_remainder_monic(parent_rem, right, modulus, counter))
                child_index += 1
            parent_index += 1
        current = nxt
    values: list[int] = []
    for rem in current:
        values.append(rem[0] % modulus if rem else 0)
    return tuple(values)


def _progression_product_polynomial(
    morphism: ProgressionProductMorphism,
    modulus: int,
    counter: _PolyCounter,
    arena: ProgressionProductArena,
) -> tuple[int, ...]:
    if morphism.modulus != int(modulus):
        raise ValueError((morphism.modulus, modulus))
    return arena.materialize(
        morphism,
        multiply=lambda left, right: _poly_mul_mod(left, right, modulus, counter),
    )


def _multipoint_evaluate_progression_monic_tree(
    polynomial: tuple[int, ...],
    progression: ProgressionProductMorphism,
    modulus: int,
    counter: _PolyCounter,
    arena: ProgressionProductArena,
) -> tuple[int, ...]:
    """Evaluate on an arithmetic progression without materializing root lists.

    The subproduct tree is the semantic split tree of ``progression``.  Each
    monic node polynomial is lowered once through ``arena`` and then reused by
    remainder descent.  This is the same exact composite-ring algorithm as the
    generic MPE path, but predictable point/product construction is represented
    by canonical morphisms instead of ad-hoc tuples.
    """
    if progression.modulus != int(modulus):
        raise ValueError((progression.modulus, modulus))
    if progression.count == 0:
        return ()
    root_poly = _progression_product_polynomial(progression, modulus, counter, arena)
    root_rem = _fast_remainder_monic(polynomial, root_poly, modulus, counter)

    root_state = (progression, root_rem)
    memo: dict[tuple[ProgressionProductMorphism, tuple[int, ...]], tuple[int, ...]] = {}
    stack: list[tuple[ProgressionProductMorphism, tuple[int, ...], bool]] = [
        (progression, root_rem, False)
    ]
    while stack:
        node, remainder, expanded = stack.pop()
        state = (node, remainder)
        if state in memo:
            continue
        if node.count == 1:
            memo[state] = (remainder[0] % modulus if remainder else 0,)
            continue
        left, right = arena.split(node)
        left_poly = _progression_product_polynomial(left, modulus, counter, arena)
        right_poly = _progression_product_polynomial(right, modulus, counter, arena)
        left_rem = _fast_remainder_monic(remainder, left_poly, modulus, counter)
        right_rem = _fast_remainder_monic(remainder, right_poly, modulus, counter)
        left_state, right_state = (left, left_rem), (right, right_rem)
        if not expanded:
            stack.append((node, remainder, True))
            stack.append((right, right_rem, False))
            stack.append((left, left_rem, False))
            continue
        memo[state] = memo[left_state] + memo[right_state]

    return memo[root_state]


def _build_rising_factorial_poly(
    width: int,
    modulus: int,
    counter: _PolyCounter,
) -> tuple[int, ...]:
    """Lower the canonical rising-factorial morphism only on demand."""
    arena = ProgressionProductArena()
    morphism = ProgressionProductMorphism(modulus, 0, -1, int(width))
    return _progression_product_polynomial(morphism, modulus, counter, arena)


