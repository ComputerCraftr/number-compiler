"""Exact finite Mahler future-predicate residuals for research cylinders.

This module owns only the semantic consumer state used by the bounded source
workspace.  Arithmetic composition remains in ``SaturatingAffineAction``;
source routing, temporal occurrences and any recursive word ports stay outside
this semantic identity.
"""

from __future__ import annotations

from dataclasses import dataclass

from number_compiler.arithmetic.fields.consumer_pullback import (
    ExactRational as Q,
)
from number_compiler.arithmetic.fields.consumer_pullback import (
    SaturatingAffineAction,
)

ZERO = Q(0)
THREE_HALVES = Q(3, 2)


def mahler_bit_action(epsilon: int) -> SaturatingAffineAction:
    """Return the exact one-bit Mahler margin action.

    The incoming margin is positive infinity at the empty prefix.  A zero bit
    has cap ``9/4`` and a one bit has cap ``3/4``; both apply the affine map
    ``3/2 * (margin - epsilon)`` to a finite incoming margin.
    """
    if type(epsilon) is not int or epsilon not in (0, 1):
        raise ValueError("Mahler epsilon must be zero or one")
    return SaturatingAffineAction(
        THREE_HALVES,
        Q(-3 * epsilon, 2),
        Q(9, 4) if epsilon == 0 else Q(3, 4),
    )


def mahler_odd_event_action(exponent: int) -> SaturatingAffineAction:
    """Exact action of one odd step followed by ``exponent-1`` even steps.

    The caller must derive this exponent from its admitted source occurrence.
    This algebraic consumer does not decide source continuation or ledger safety.
    """
    if type(exponent) is not int or exponent < 1:
        raise ValueError("Mahler odd-event exponent must be positive")
    scale = Q(3**exponent, 1 << exponent)
    # (3/4)*(3/2)^(q-1) = (3/2)^q/2. Both caps are
    # retained by the shared saturating action, without a temporal bit word.
    return SaturatingAffineAction(scale, -scale, min(Q(9, 4), scale / Q(2)))


@dataclass(frozen=True, slots=True)
class MahlerPredicateState:
    """Exact right-congruence residual of the finite Mahler safety consumer."""

    forbidden: bool = False
    margin: Q | None = None

    def __post_init__(self) -> None:
        if type(self.forbidden) is not bool:
            raise TypeError("Mahler predicate flag must be boolean")
        if self.margin is not None and type(self.margin) is not Q:
            raise TypeError("Mahler predicate margin must be exact rational")
        if self.margin is not None:
            self.margin.validate()
        if self.forbidden and self.margin is not None:
            raise ValueError("forbidden Mahler state cannot retain a margin")
        if not self.forbidden and self.margin is not None and self.margin <= ZERO:
            raise ValueError("live Mahler margin must be positive")

    @classmethod
    def initial(cls) -> MahlerPredicateState:
        """Return the empty-prefix state, whose margin is positive infinity."""
        return cls(False, None)

    @classmethod
    def failed(cls) -> MahlerPredicateState:
        return cls(True, None)

    def advance_action(self, action: SaturatingAffineAction) -> MahlerPredicateState:
        """Consume one composed action without replaying its symbols."""
        if type(action) is not SaturatingAffineAction:
            raise TypeError("Mahler predicate requires an exact affine action")
        # Every action generated by the Mahler bit grammar has nonpositive
        # offset.  Without this admission check a caller could apply a
        # positive-offset action after a failed finite margin, contradicting
        # the absorbing FORBIDDEN representation.
        if action.offset > ZERO:
            raise ValueError("Mahler predicate actions require a nonpositive offset")
        if self.forbidden:
            return self
        value = action.apply(self.margin)
        if value is None:
            return self
        if value <= ZERO:
            return self.failed()
        return MahlerPredicateState(False, value)

    def advance_bit(self, epsilon: int) -> MahlerPredicateState:
        return self.advance_action(mahler_bit_action(epsilon))

    @property
    def semantic_key(self) -> tuple[object, ...]:
        if self.forbidden:
            return ("mahler-predicate", "FORBIDDEN")
        if self.margin is None:
            return ("mahler-predicate", "INFINITY")
        return ("mahler-predicate", self.margin.numerator, self.margin.denominator)


__all__ = ["MahlerPredicateState", "mahler_bit_action", "mahler_odd_event_action"]
