def fermat_germ(value: int) -> int:
    """The exact multiplicative difference germ ``P(e)=e^2+2e``."""
    value = int(value)
    return value * value + 2 * value


def fermat_deck(value: int) -> int:
    """Exchange the two sheets of ``P(e)=z``."""
    return -int(value) - 2


def fermat_tangent(value: int) -> int:
    """Derivative of the germ; it is anti-invariant under the deck action."""
    return 2 * (int(value) + 1)


def mersenne_half_angle(value: int) -> int:
    """Trace coordinate below the half-angle cover: ``T=U^2-2``."""
    value = int(value)
    return value * value - 2


def mersenne_deck(value: int) -> int:
    return -int(value)


def mersenne_tangent(value: int) -> int:
    return 2 * int(value)


@dataclass(frozen=True, slots=True)
class PolynomialDeckAudit:
    fermat_same_quotient: bool
    fermat_tangent_changes_sign: bool
    fermat_tangent_square_descends: bool
    mersenne_same_quotient: bool
    mersenne_tangent_changes_sign: bool
    mersenne_tangent_square_descends: bool
    invariant_state_sees_orientation: bool = False
    anti_invariant_requires_square_root: bool = True


def polynomial_deck_audit(sample: int = 37) -> PolynomialDeckAudit:
    """Verify the exact invariant/anti-invariant identities on one integer seed.

    These are polynomial identities, not probabilistic tests; the sample merely
    makes them executable guards without a symbolic dependency.
    """
    e = int(sample)
    je = fermat_deck(e)
    u = e + 5
    ju = mersenne_deck(u)
    z = fermat_germ(e)
    t = mersenne_half_angle(u)
    return PolynomialDeckAudit(
        fermat_same_quotient=fermat_germ(je) == z,
        fermat_tangent_changes_sign=fermat_tangent(je) == -fermat_tangent(e),
        fermat_tangent_square_descends=fermat_tangent(e) ** 2 == 4 * (z + 1),
        mersenne_same_quotient=mersenne_half_angle(ju) == t,
        mersenne_tangent_changes_sign=mersenne_tangent(ju) == -mersenne_tangent(u),
        mersenne_tangent_square_descends=mersenne_tangent(u) ** 2 == 4 * (t + 2),
    )


@dataclass(frozen=True, slots=True)
class IteratedGermConjugacyAudit:
    sample: int
    steps: int
    iterated_germ: int
    closed_form: int
    exact: bool
    deck_same_after_iteration: bool
    multiplication_depth_required_generically: int


def iterated_germ_conjugacy_audit(
    sample: int = 3, steps: int = 6
) -> IteratedGermConjugacyAudit:
    """Audit ``P^r(e)+1=(e+1)^(2^r)`` for the Fermat germ.

    The identity is proved algebraically by ``1+P(e)=(1+e)^2`` and induction;
    this bounded execution is a regression guard.  It also records the generic
    multiplication-depth lower bound: a straight-line program starting from an
    unconstrained sheet coordinate needs at least ``r`` multiplications to reach
    degree ``2^r``.  Binary composition compresses the *description* of the
    iterate, not evaluation of the missing anti-invariant source.
    """
    e, r = int(sample), int(steps)
    if r < 0 or r > 12:
        raise ValueError(r)
    value = e
    other = fermat_deck(e)
    for _ in range(r):
        value = fermat_germ(value)
        other = fermat_germ(other)
    closed = pow(e + 1, 1 << r) - 1
    return IteratedGermConjugacyAudit(
        e,
        r,
        value,
        closed,
        value == closed,
        value == other,
        r,
    )


@dataclass(frozen=True, slots=True)
class SparseFermatCarryAudit:
    parameter: int
    modulus: int
    factors: tuple[int, int]
    minimum_factor_v2: int
    odd_quotients: tuple[int, int]
    first_symmetric_coefficient: int
    second_symmetric_coefficient: int
    first_coefficient_v2: int
    minimum_depth_multiplicity: int
    parity_constraint_only: bool
    exact_sparse_product: bool
    candidate_derived: bool = False


def fermat_f5_sparse_carry_audit() -> SparseFermatCarryAudit:
    """Exact F5 control for the sparse-product/carry cancellation.

    This deliberately uses the known F5 factors only as a research differential.
    With ``q_i=1+2^B k_i`` both minimum-depth germs are locally bad, yet their
    first symmetric coefficient gains seven extra powers of two.  The single
    product equation therefore exposes aggregate carries, not local support.
    """
    n = 5
    N = fermat_number(n)
    factors = (641, 6700417)
    if prod(factors) != N:
        raise AssertionError((factors, N))
    depths = tuple(v2_nonzero(q - 1) for q in factors)
    B = min(depths)
    if depths != (B, B):
        raise AssertionError(depths)
    ks = ((factors[0] - 1) >> B, (factors[1] - 1) >> B)
    if not all(k & 1 for k in ks):
        raise AssertionError(ks)
    e1 = sum(ks)
    e2 = prod(ks)
    K = 1 << n
    exact = e1 + (1 << B) * e2 == (1 << (K - B))
    return SparseFermatCarryAudit(
        n,
        N,
        factors,
        B,
        ks,
        e1,
        e2,
        v2_nonzero(e1),
        2,
        True,
        exact,
    )


@dataclass(frozen=True, slots=True)
class GermOrientationAudit:
    family: str
    parameter: int
    spec: SpecialFrobeniusChunkSpec
    modulus: int
    local_factors: tuple[int, ...]
    local_depths: tuple[int, ...]
    local_orientations: tuple[int, ...]
    crt_orientation: int
    orientation_defect: int
    result: SpecialFrobeniusChunkResult
    scalar_character: int
    all_local_pass: bool
    factor_enumeration: int
    candidate_derived: bool = False

    @property
    def orientation_is_involution(self) -> bool:
        return pow(self.crt_orientation, 2, self.modulus) == 1 % self.modulus

    @property
    def support_exact(self) -> bool:
        passing = prod(
            q
            for q, bit in zip(self.local_factors, self.local_orientations, strict=True)
            if bit == 1
        )
        return (
            self.result.status
            == (
                "ALL_PASS"
                if passing == self.modulus
                else "ALL_FAIL"
                if passing == 1
                else "SPLIT"
            )
            and gcd(self.orientation_defect, self.modulus) == passing
        )


def crt_pairwise(residues: tuple[int, ...], moduli: tuple[int, ...]) -> int:
    if len(residues) != len(moduli) or not moduli:
        raise ValueError((residues, moduli))
    modulus = prod(moduli)
    out = 0
    for residue, q in zip(residues, moduli, strict=True):
        if q <= 1 or modulus % q:
            raise ValueError(q)
        rest = modulus // q
        if gcd(rest, q) != 1:
            raise ValueError("CRT audit requires pairwise-coprime components")
        out += (int(residue) % q) * rest * pow(rest, -1, q)
    return out % modulus


def _orientation_audit_from_parts(
    family: str,
    parameter: int,
    spec: SpecialFrobeniusChunkSpec,
    modulus: int,
    factors: tuple[int, ...],
    depths: tuple[int, ...],
) -> GermOrientationAudit:
    if prod(factors) != modulus:
        raise ValueError(
            "orientation audit requires a complete squarefree factor control"
        )
    orientations = tuple(1 if depth >= spec.end_level else -1 for depth in depths)
    b = crt_pairwise(orientations, factors)
    defect = (b - 1) % modulus
    packet = SpecialFrobeniusDefectPacket(
        spec,
        modulus,
        defect,
        "factor-truth-germ-descent-orientation",
        candidate_derived=False,
    )
    result = packet.classify()
    character = prod(orientations)
    return GermOrientationAudit(
        family,
        parameter,
        spec,
        modulus,
        factors,
        depths,
        orientations,
        b,
        defect,
        result,
        character,
        all(bit == 1 for bit in orientations),
        len(factors),
    )


def prime_decision_orientation_truth_audit(
    family: str,
    parameter: int,
) -> GermOrientationAudit:
    """Factor-backed orientation at exactly the production prime-decision chunk."""
    threshold = terminal_threshold_spec(family, parameter)
    spec = prime_decision_chunk_spec(threshold)
    truth = ambient_capacity_truth(family, parameter)
    return _orientation_audit_from_parts(
        family,
        parameter,
        spec,
        truth.modulus,
        truth.local_factors,
        truth.local_lift_depths,
    )


def mersenne_m29_mixed_orientation_audit() -> GermOrientationAudit:
    """Exact mixed-support control: at level one only 2089 passes for M29."""
    row = next(item for item in mixed_capacity_controls() if item.family == "mersenne")
    if row.parameter != 29 or not row.factor_witnesses_valid:
        raise AssertionError(row)
    modulus = mersenne_number(29)
    if prod(row.supplied_factors) != modulus:
        raise AssertionError(row.supplied_factors)
    spec = SpecialFrobeniusChunkSpec("mersenne", 29, 1, 1, 2, modulus.bit_length())
    return _orientation_audit_from_parts(
        "mersenne",
        29,
        spec,
        modulus,
        row.supplied_factors,
        row.local_lift_depths,
    )


@dataclass(frozen=True, slots=True)
class CharacterSupportAudit:
    local_rank: int
    orientation_vectors: int
    walsh_characters_required_for_exact_all_pass: int
    product_character_collision: bool
    nonlinear_support_packet_avoids_collision: bool


def character_support_audit(local_rank: int = 2) -> CharacterSupportAudit:
    """Fourier-size guard for replacing support by aggregate C2 characters.

    On ``G=(C2)^r`` the indicator of the identity has nonzero Fourier
    coefficient on every character.  Therefore an exact *linear character*
    representation of ALL_PASS needs all ``2^r`` characters.  This does not
    rule out the nonlinear gcd packet; it explains why a fixed scalar/character
    vector cannot substitute for that packet.
    """
    r = int(local_rank)
    if r < 1:
        raise ValueError(r)
    size = 1 << r
    # (+,+,...) and a vector with two minus signs have the same product
    # character as soon as r >= 2, despite opposite ALL_PASS truth.
    collision = r >= 2
    return CharacterSupportAudit(r, size, size, collision, True)


@dataclass(frozen=True, slots=True)
class CyclotomicThresholdCollapseAudit:
    family: str
    parameter: int
    modulus_bits: int
    required_local_v2: int
    conductor_log2: int
    dense_character_degree_log2: int
    candidate_residue_kind: str
    quotient_orbit_order: int
    base_ring_section_required: bool
    explicit_dense_state_compact: bool
    candidate_derived: bool = True
    factor_enumeration: int = 0


def cyclotomic_threshold_collapse_audit(
    family: str,
    parameter: int,
) -> CyclotomicThresholdCollapseAudit:
    """Audit the direct cyclotomic/APR route at the shortened release threshold.

    No ``2^v`` object is materialized.  ``dense_character_degree_log2=v-1``
    records ``phi(2^v)=2^(v-1)`` symbolically.
    """
    spec = terminal_threshold_spec(family, parameter)
    v = spec.prime_decision_required_local_v2
    if v < 2:
        raise ValueError((family, parameter, v))
    if family == "fermat":
        modulus = fermat_number(parameter)
        # v <= 2^n and F_n = 1 + 2^(2^n).
        if modulus % (1 << v) != 1:
            raise AssertionError((family, parameter, v))
        residue_kind = "+1"
        orbit_order = 1
    elif family == "mersenne":
        modulus = mersenne_number(parameter)
        residue = modulus % (1 << v)
        if residue != (1 << v) - 1:
            raise AssertionError((family, parameter, v, residue))
        residue_kind = "-1 modulo sign"
        # In the real cyclotomic quotient +/-1 are the same class.
        orbit_order = 1
    else:
        raise ValueError(family)
    return CyclotomicThresholdCollapseAudit(
        family,
        int(parameter),
        modulus.bit_length(),
        v,
        v,
        v - 1,
        residue_kind,
        orbit_order,
        True,
        False,
    )


