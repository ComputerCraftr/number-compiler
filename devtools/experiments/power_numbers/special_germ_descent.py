"""Exact descent/orientation frontier for the terminal special-number germ.

This module asks the question left open by :mod:`number_compiler.sequences.power_numbers.germ`:
can the polynomial perturbation itself manufacture the first support bit?

The answer inside the polynomial-germ category is no, for an exact reason.  The
Fermat perturbation

    P(e) = e^2 + 2e

is the quotient by the deck involution ``j(e)=-e-2``.  Its invariant algebra is
generated by ``P(e)``; the anti-invariant line is generated by ``e+1`` and

    (e+1)^2 = P(e)+1.

Thus every root-exchange-invariant polynomial transducer factors through the
already-known circle coordinate, while every orientation-sensitive polynomial
contains the same square-root coordinate whose field of definition is the
missing quadratic-etale query.  The Mersenne half-angle cover has the identical
structure with ``U -> -U`` and ``U^2=T+2``.

The factor-backed routines below are audits only.  They construct the
ring-valued local orientation ``b`` (``+1`` on passing components, ``-1`` on
failing components) to verify that ``D=b-1`` is exactly the desired
``SpecialFrobeniusDefectPacket``.  Production must not import this module.

A second audit records why a direct cyclotomic/APR escape does not create a
compact source coordinate at the release threshold.  The candidate is already
``+/-1`` modulo the required two-power conductor, so the relevant cyclotomic
orbit has order one after the real sign quotient.  The desired primitive phase
must therefore be a base-ring section itself; an explicit cyclotomic character
has degree ``phi(2^v)=2^(v-1)``.  This is a representation of the same source
query, not a new constructor.
"""

