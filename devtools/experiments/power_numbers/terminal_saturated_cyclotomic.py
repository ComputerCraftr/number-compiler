"""Two-power cyclotomic-extension formulation of the terminal special selector.

This module tests a classical cyclotomy route against the exact v0.51 theorem
frontier.  For ``s=2**v`` an s-th cyclotomic extension of ``Z/NZ`` exists iff
all prime divisors q of N lie in the subgroup generated by ``N mod s``.
At the shortened prime-decision thresholds this is exactly the required local
congruence:

* Fermat: N == +1 (mod s), so every q must be +1 (mod s);
* Mersenne: N == -1 (mod s), so every q must be +/-1 (mod s).

Thus cyclotomic-extension *existence* is a perfect semantic quotient for the
release bit.  The important question is whether its witness can be constructed
more cheaply than the already-known Lucas/Pepin chain.  The degree is only one
for Fermat and two for Mersenne, but the witness must still have primitive
2-power order s.  The cost audit below records that the obvious fixed special
witnesses collapse exactly to the old high-order root/trace extraction problem;
this module therefore remains research-only and does not authorize production
PASS.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import prod

from number_compiler.sequences.power_numbers.numbers import (
    fermat_number,
    mersenne_number,
)
from number_compiler.sequences.power_numbers.terminal_threshold import (
    terminal_threshold_spec,
)


@dataclass(frozen=True, slots=True)
class TwoPowerCyclotomicCriterion:
    family: str
    parameter: int
    modulus: int
    conductor_v2: int
    conductor: int
    frobenius_degree: int
    candidate_residue: int
    subgroup_residues: tuple[int, ...]
    prime_decision_equivalent: bool
    proof_method: str

    @property
    def descriptor_bits(self) -> int:
        return (
            max(1, self.parameter.bit_length())
            + max(1, self.conductor_v2.bit_length())
            + 4
        )

    def local_factor_passes(self, q: int) -> bool:
        q = int(q)
        if q <= 1 or self.modulus % q:
            raise ValueError((q, self.modulus))
        return (q % self.conductor) in self.subgroup_residues


@dataclass(frozen=True, slots=True)
class CyclotomicFactorAudit:
    criterion: TwoPowerCyclotomicCriterion
    factors: tuple[int, ...]
    residues: tuple[int, ...]
    local_passes: tuple[bool, ...]
    extension_exists_by_factor_truth: bool
    agrees_with_prime_truth: bool
    factor_truth_only: bool = True
    factor_enumeration: int = 0


@dataclass(frozen=True, slots=True)
class CyclotomicWitnessCostAudit:
    criterion: TwoPowerCyclotomicCriterion
    witness_model: str
    construction_squarings: int
    order_verification_squarings: int
    total_sequential_squarings: int
    classical_horizon: int
    cheaper_than_classical_chain: bool
    candidate_derived_compact_constructor_known: bool
    interpretation: str


def terminal_two_power_cyclotomic_criterion(
    family: str,
    parameter: int,
) -> TwoPowerCyclotomicCriterion:
    spec = terminal_threshold_spec(str(family), int(parameter))
    v = spec.prime_decision_required_local_v2
    if v < 2:
        raise ValueError((spec.family, spec.parameter, v))
    s = 1 << v
    if spec.family == "fermat":
        candidate = fermat_number(spec.parameter)
        residue = candidate % s
        if residue != 1:
            raise AssertionError((candidate, s, residue))
        subgroup: tuple[int, ...] = (1,)
        degree = 1
        method = "lenstra-cyclotomic-extension:<N-mod-2^v>={1}"
    else:
        candidate = mersenne_number(spec.parameter)
        residue = candidate % s
        # The threshold never exceeds p, so M_p == -1 modulo 2^v.
        if residue != s - 1:
            raise AssertionError((candidate, s, residue))
        subgroup = (1, s - 1)
        degree = 2
        method = "lenstra-cyclotomic-extension:<N-mod-2^v>={+/-1}"
    return TwoPowerCyclotomicCriterion(
        spec.family,
        spec.parameter,
        candidate,
        v,
        s,
        degree,
        residue,
        subgroup,
        True,
        method,
    )


def cyclotomic_factor_audit(
    family: str,
    parameter: int,
    factors: tuple[int, ...],
) -> CyclotomicFactorAudit:
    criterion = terminal_two_power_cyclotomic_criterion(family, parameter)
    ff = tuple(int(q) for q in factors)
    if not ff or prod(ff) != criterion.modulus:
        raise ValueError((ff, criterion.modulus))
    residues = tuple(q % criterion.conductor for q in ff)
    passes = tuple(r in criterion.subgroup_residues for r in residues)
    exists = all(passes)
    # The shortened threshold theorem makes all-local pass equivalent to prime
    # for the special family.  In this factor-backed audit, one factor means the
    # candidate itself is prime; several factors means composite.
    prime_truth = len(ff) == 1 and ff[0] == criterion.modulus
    return CyclotomicFactorAudit(
        criterion,
        ff,
        residues,
        passes,
        exists,
        exists == prime_truth,
    )


def cyclotomic_witness_cost_audit(
    family: str,
    parameter: int,
) -> CyclotomicWitnessCostAudit:
    """Audit the obvious fixed witness against the classical sequential chain.

    Fermat prime case: base 3 has full 2-power order.  Projecting it to a
    primitive 2^v root takes W-v squarings and certifying exact order takes
    v-1 more, totaling W-1: the Pepin chain length.

    Mersenne prime case: the norm-one unit 2+sqrt(3) has order 2^p.  Projecting
    it to order 2^v takes p-v squarings and certifying the resulting primitive
    root takes v-1 more, totaling p-1 (the same linear-depth order extraction;
    trace normalization saves only a constant versus the LL presentation).
    """
    c = terminal_two_power_cyclotomic_criterion(family, parameter)
    v = c.conductor_v2
    if c.family == "fermat":
        W = 1 << c.parameter
        construction = W - v
        verification = v - 1
        classical = W - 1
        model = "degree-1 primitive root from fixed Pepin generator 3"
        interpretation = (
            "Cyclotomic degree is one, but constructing and proving a primitive "
            "2^v root from the fixed special generator uses exactly the full "
            "W-1 squaring chain.  Extension existence is the desired theorem "
            "semantically, not a faster source constructor."
        )
    else:
        p = c.parameter
        construction = p - v
        verification = v - 1
        classical = p - 1
        model = "degree-2 primitive root from norm-one unit 2+sqrt(3)"
        interpretation = (
            "Cyclotomic degree is two, but projecting 2+sqrt(3) to order 2^v "
            "and verifying that order still costs p-1 sequential squarings "
            "up to the constant trace normalization of Lucas-Lehmer."
        )
    total = construction + verification
    if total != classical:
        raise AssertionError((c.family, c.parameter, total, classical))
    return CyclotomicWitnessCostAudit(
        c,
        model,
        construction,
        verification,
        total,
        classical,
        False,
        False,
        interpretation,
    )


def candidate_saturated_cyclotomic_probe(
    family: str,
    parameter: int,
) -> dict[str, object]:
    """Fail-closed candidate constructor status.

    The criterion is exact, but no compact constructor for its primitive-root
    witness is known.  In particular, this function never manufactures a
    degree-1/2 witness from a supplied prime label or from factor truth.
    """
    c = terminal_two_power_cyclotomic_criterion(family, parameter)
    return {
        "family": c.family,
        "parameter": c.parameter,
        "status": "UNKNOWN",
        "method": "candidate-saturated-cyclotomic-witness-unavailable",
        "frobenius_degree": c.frobenius_degree,
        "conductor_v2": c.conductor_v2,
        "descriptor_bits": c.descriptor_bits,
        "factor_enumeration": 0,
        "raw_specialization_squarings": 0,
        "candidate_derived_witness": None,
    }
