"""Canonical finite cell identities for directed arithmetic spacetime fields.

The evolving integer may have unbounded extent, but the *local* semantic
alphabet used by carry/domain kernels must remain bounded.  This module keeps
those concerns separate:

* :class:`NormalizedDomainFrame` stores active length only as dyadic occurrence
  geometry.  Its leaves are the fixed alphabet ``{inactive, active}``.
* :class:`DomainCellCodec` interns bounded semantic cell payloads to integer
  symbols suitable for :mod:`number_compiler.arithmetic.fields.dyadic_tile`.
* :class:`CanonicalDomainArena` quotients tile content by the causal symmetry
  generated by spatial reflection and an optional proved value conjugacy.

The symmetry group is the four-element causal subgroup generated by two
commuting involutions (mirror and conjugate).  It is the part of a D4-style
spacetime symmetry that is valid for arithmetic transducers.  **It never flips
physical carry causality.**  A carry always enters at the least-significant
boundary and exits toward the most-significant boundary; a mirrored canonical
representative is interpreted with the reverse *word action*, exactly as in
``OrientedFiniteActionArena``, rather than by propagating a real carry backward.
"""

from __future__ import annotations

import weakref
from collections.abc import Callable, Hashable
from dataclasses import dataclass
from enum import Enum

from number_compiler.arithmetic.automata.symmetry_powering import ActionTransform
from number_compiler.arithmetic.contracts.input_validation import is_object_tuple
from number_compiler.arithmetic.fields.dyadic_tile import (
    DyadicSpan,
    DyadicTile,
    join,
    leaf,
    prefix_domain_span,
)


class CarryDirection(Enum):
    """Only physical carry direction supported by causal arithmetic fields."""

    TOWARD_MSD = "lsd-to-msd"


@dataclass(frozen=True, slots=True)
class DomainCell:
    """One bounded semantic leaf.

    ``payload`` must come from a family-specific finite alphabet.  Absolute
    coordinate, active length, generation, and temporal exponent are forbidden
    from this object and belong to surrounding dyadic geometry/metadata.
    """

    family: str
    active: bool
    payload: Hashable

    @property
    def canonical_key(self) -> tuple[object, ...]:
        return ("domain-cell", self.family, bool(self.active), self.payload)


class DomainCellCodec:
    """Intern semantic cells and a proved involutive conjugacy."""

    __slots__ = ("_cells", "_conjugate", "_conjugate_ids", "_ids", "family")

    def __init__(
        self,
        family: str,
        *,
        conjugate: Callable[[DomainCell], DomainCell] | None = None,
    ) -> None:
        family = str(family)
        if not family:
            raise ValueError(family)
        self.family = family
        self._cells: list[DomainCell] = []
        self._ids: dict[DomainCell, int] = {}
        self._conjugate = conjugate
        self._conjugate_ids: dict[int, int] = {}

    def intern(self, cell: DomainCell) -> int:
        if type(cell) is not DomainCell or cell.family != self.family:
            raise ValueError((self.family, cell))
        found = self._ids.get(cell)
        if found is not None:
            return found
        symbol = len(self._cells)
        self._cells.append(cell)
        self._ids[cell] = symbol
        return symbol

    def cell(self, symbol: int) -> DomainCell:
        return self._cells[int(symbol)]

    def conjugate_symbol(self, symbol: int) -> int:
        symbol = int(symbol)
        if self._conjugate is None:
            return symbol
        found = self._conjugate_ids.get(symbol)
        if found is not None:
            return found
        source = self.cell(symbol)
        target = self._conjugate(source)
        if type(target) is not DomainCell or target.family != self.family:
            raise ValueError((source, target))
        if self._conjugate(target) != source:
            raise ValueError(("non-involutive-domain-conjugacy", source, target))
        out = self.intern(target)
        self._conjugate_ids[symbol] = out
        self._conjugate_ids[out] = symbol
        return out

    @property
    def alphabet_size(self) -> int:
        return len(self._cells)

    @property
    def has_conjugacy(self) -> bool:
        return self._conjugate is not None


@dataclass(frozen=True, slots=True)
class CanonicalDomainRef:
    """Canonical content tile plus transform from physical to canonical view."""

    tile: DyadicTile
    transform: ActionTransform


@dataclass(frozen=True, slots=True)
class NormalizedDomainFrame:
    """Active-prefix geometry with a fixed local alphabet.

    ``active_length`` is deliberately geometry, not part of any leaf/carry
    symbol.  The dyadic forest therefore represents arbitrarily long fields in
    O(logical_length.bit_length()) uniform chunks when the domain is uniform.
    """

    active_length: int
    logical_length: int
    span: DyadicSpan

    @classmethod
    def prefix(cls, active_length: int, logical_length: int) -> NormalizedDomainFrame:
        active_length, logical_length = int(active_length), int(logical_length)
        return cls(
            active_length,
            logical_length,
            prefix_domain_span(active_length, logical_length),
        )

    def __post_init__(self) -> None:
        if not 0 <= int(self.active_length) <= int(self.logical_length):
            raise ValueError((self.active_length, self.logical_length))
        if self.span.start != 0 or self.span.length != int(self.logical_length):
            raise ValueError((self.span.start, self.span.length, self.logical_length))

    @property
    def geometry_bits(self) -> int:
        return max(1, int(self.active_length).bit_length()) + max(
            1, int(self.logical_length).bit_length()
        )

    @property
    def canonical_key(self) -> tuple[object, ...]:
        # Extent is geometry-level metadata.  It is allowed here, but never in a
        # finite cell/action alphabet.
        return (
            "normalized-domain-frame",
            self.active_length,
            self.logical_length,
            tuple(chunk.tile for chunk in self.span.chunks),
        )


class CanonicalDomainArena:
    """Canonicalize dyadic domain/content tiles under causal mirror/conjugacy."""

    __slots__ = (
        "_canonical_hits",
        "_conjugate",
        "_conjugate_hits",
        "_keys",
        "_mirror",
        "_mirror_hits",
        "_refs",
        "carry_direction",
        "codec",
    )

    def __init__(self, codec: DomainCellCodec) -> None:
        self.codec = codec
        self.carry_direction = CarryDirection.TOWARD_MSD
        self._mirror: weakref.WeakKeyDictionary[DyadicTile, DyadicTile] = (
            weakref.WeakKeyDictionary()
        )
        self._conjugate: weakref.WeakKeyDictionary[DyadicTile, DyadicTile] = (
            weakref.WeakKeyDictionary()
        )
        self._refs: weakref.WeakKeyDictionary[DyadicTile, CanonicalDomainRef] = (
            weakref.WeakKeyDictionary()
        )
        self._keys: weakref.WeakKeyDictionary[DyadicTile, tuple[object, ...]] = (
            weakref.WeakKeyDictionary()
        )
        self._mirror_hits = self._conjugate_hits = self._canonical_hits = 0

    def structural_key(self, tile: DyadicTile) -> tuple[object, ...]:
        found = self._keys.get(tile)
        if found is not None:
            return found
        built: dict[DyadicTile, tuple[object, ...]] = {}
        stack: list[tuple[DyadicTile, bool]] = [(tile, False)]
        while stack:
            node, ready = stack.pop()
            cached = self._keys.get(node)
            if cached is not None:
                built[node] = cached
                continue
            if node.level == 0:
                if node.symbol is None:
                    raise AssertionError(node)
                key: tuple[object, ...] = (0, int(node.symbol))
                self._keys[node] = key
                built[node] = key
                continue
            if node.left is None or node.right is None:
                raise AssertionError(node)
            if not ready:
                stack.append((node, True))
                if node.right not in built and node.right not in self._keys:
                    stack.append((node.right, False))
                if node.left not in built and node.left not in self._keys:
                    stack.append((node.left, False))
                continue
            lk = self._keys.get(node.left, built.get(node.left))
            rk = self._keys.get(node.right, built.get(node.right))
            if lk is None or rk is None:
                raise AssertionError(node)
            key = (node.level, lk, rk)
            self._keys[node] = key
            built[node] = key
        return self._keys[tile]

    def mirror(self, tile: DyadicTile) -> DyadicTile:
        found = self._mirror.get(tile)
        if found is not None:
            self._mirror_hits += 1
            return found
        built: dict[DyadicTile, DyadicTile] = {}
        stack: list[tuple[DyadicTile, bool]] = [(tile, False)]
        while stack:
            node, ready = stack.pop()
            cached = self._mirror.get(node)
            if cached is not None:
                built[node] = cached
                continue
            if node.level == 0:
                if node.symbol is None:
                    raise AssertionError(node)
                out = leaf(int(node.symbol))
                self._mirror[node] = out
                self._mirror[out] = node
                built[node] = out
                continue
            if node.left is None or node.right is None:
                raise AssertionError(node)
            if not ready:
                stack.append((node, True))
                if node.left not in built and node.left not in self._mirror:
                    stack.append((node.left, False))
                if node.right not in built and node.right not in self._mirror:
                    stack.append((node.right, False))
                continue
            ml = self._mirror.get(node.left, built.get(node.left))
            mr = self._mirror.get(node.right, built.get(node.right))
            if ml is None or mr is None:
                raise AssertionError(node)
            out = join(mr, ml)
            self._mirror[node] = out
            self._mirror[out] = node
            built[node] = out
        return self._mirror[tile]

    def conjugate(self, tile: DyadicTile) -> DyadicTile:
        found = self._conjugate.get(tile)
        if found is not None:
            self._conjugate_hits += 1
            return found
        built: dict[DyadicTile, DyadicTile] = {}
        stack: list[tuple[DyadicTile, bool]] = [(tile, False)]
        while stack:
            node, ready = stack.pop()
            cached = self._conjugate.get(node)
            if cached is not None:
                built[node] = cached
                continue
            if node.level == 0:
                if node.symbol is None:
                    raise AssertionError(node)
                out = leaf(self.codec.conjugate_symbol(int(node.symbol)))
                self._conjugate[node] = out
                self._conjugate[out] = node
                built[node] = out
                continue
            if node.left is None or node.right is None:
                raise AssertionError(node)
            if not ready:
                stack.append((node, True))
                if node.right not in built and node.right not in self._conjugate:
                    stack.append((node.right, False))
                if node.left not in built and node.left not in self._conjugate:
                    stack.append((node.left, False))
                continue
            left = self._conjugate.get(node.left, built.get(node.left))
            right = self._conjugate.get(node.right, built.get(node.right))
            if left is None or right is None:
                raise AssertionError(node)
            out = join(left, right)
            self._conjugate[node] = out
            self._conjugate[out] = node
            built[node] = out
        return self._conjugate[tile]

    def transformed(self, tile: DyadicTile, transform: ActionTransform) -> DyadicTile:
        out = tile
        if transform & ActionTransform.CONJUGATE:
            out = self.conjugate(out)
        if transform & ActionTransform.MIRROR:
            out = self.mirror(out)
        return out

    def canonical_ref(self, tile: DyadicTile) -> CanonicalDomainRef:
        found = self._refs.get(tile)
        if found is not None:
            self._canonical_hits += 1
            return found
        transforms: tuple[ActionTransform, ...] = (
            ActionTransform.IDENTITY,
            ActionTransform.MIRROR,
        )
        if self.codec.has_conjugacy:
            transforms += (
                ActionTransform.CONJUGATE,
                ActionTransform.MIRROR | ActionTransform.CONJUGATE,
            )
        candidates = [(self.transformed(tile, t), t) for t in transforms]
        representative, transform = min(
            candidates, key=lambda item: (self.structural_key(item[0]), int(item[1]))
        )
        ref = CanonicalDomainRef(representative, transform)
        self._refs[tile] = ref
        return ref

    def metrics(self) -> dict[str, int | str]:
        return {
            "canonical_refs": len(self._refs),
            "mirror_cache": len(self._mirror),
            "conjugate_cache": len(self._conjugate),
            "mirror_hits": self._mirror_hits,
            "conjugate_hits": self._conjugate_hits,
            "canonical_hits": self._canonical_hits,
            "carry_direction": self.carry_direction.value,
        }


def _complement_cell(cell: DomainCell, maximum: int, family: str) -> DomainCell:
    if not cell.active:
        return cell
    if not isinstance(cell.payload, int):
        raise TypeError(cell.payload)
    value = int(cell.payload)
    if not 0 <= value <= maximum:
        raise ValueError(cell)
    return DomainCell(family, True, maximum - value)


def reverse_pair_codec(base: int = 10) -> DomainCellCodec:
    """Finite symmetric-pair alphabet used by reverse/add spacetime cells.

    Active symbols are interned in numerical pair-sum order, so IDs
    ``0..2*(base-1)`` coincide with the existing pair-field alphabet.  One
    inactive exterior symbol follows them.  Conjugacy is the exact pair-sum
    complement ``S -> 2(base-1)-S``; inactive exterior is a fixed point.
    """
    base = int(base)
    if base < 2:
        raise ValueError(base)
    family = f"reverse-add-pair-b{base}"

    def conjugate(cell: DomainCell) -> DomainCell:
        return _complement_cell(cell, 2 * (base - 1), family)

    codec = DomainCellCodec(family, conjugate=conjugate)
    for value in range(2 * base - 1):
        symbol = codec.intern(DomainCell(family, True, value))
        if symbol != value:
            raise AssertionError((symbol, value))
    codec.intern(DomainCell(family, False, 0))
    return codec


def reverse_history_codec(base: int, horizon: int) -> DomainCellCodec:
    """Codec for one vertical H-row carry/domain column.

    Payload is ``(carry_bits, active_bits)``.  Both masks have exactly H logical
    bits, so the alphabet is finite for fixed radix.  Conjugacy flips carry
    bits only where that historical row is active; inactive exterior stays a
    fixed point and therefore cannot alias an active zero-carry cell.
    """

    base, horizon = int(base), int(horizon)
    if base < 3 or horizon <= 0:
        raise ValueError((base, horizon))
    mask = (1 << horizon) - 1

    def conjugate(cell: DomainCell) -> DomainCell:
        if not cell.active:
            return cell
        payload = cell.payload
        if not is_object_tuple(payload) or len(payload) != 2:
            raise TypeError(payload)
        carry_bits, active_bits = payload
        if type(carry_bits) is not int or type(active_bits) is not int:
            raise TypeError(payload)
        active_bits &= mask
        carry_bits &= active_bits
        return DomainCell(
            cell.family,
            True,
            ((carry_bits ^ active_bits) & mask, active_bits),
        )

    return DomainCellCodec(f"reverse-add-carry-h{horizon}-b{base}", conjugate=conjugate)


def collatz_digit_codec(base: int = 4) -> DomainCellCodec:
    """Finite active/inactive radix digit codec with digit-complement conjugacy."""

    base = int(base)
    if base < 3:
        raise ValueError(base)

    def conjugate(cell: DomainCell) -> DomainCell:
        return _complement_cell(cell, base - 1, cell.family)

    return DomainCellCodec(f"collatz-radix-{base}", conjugate=conjugate)


