"""Exact radix-digit formulas and synthesized finite-state arithmetic monoids.

This module generalizes the carry-prefix construction used by reverse-and-add.
A digit transducer is a finite Mealy machine.  Each input digit induces a
function on the finite control state set; the closure of those functions under
composition is the transition monoid.  A parallel prefix scan of that monoid is
compiled into :class:`FormulaArena` Boolean position formulas in O(log width)
formula depth (for fixed monoid size).

The resulting :class:`FormulaRoot` reconstructs every output digit exactly.  It
is not a sampled fingerprint and is independent of any particular orbit/seed.
"""

