@dataclass(frozen=True, slots=True)
class DigitSpec:
    base: int = 2

    def __post_init__(self) -> None:
        if self.base < 2:
            raise ValueError("base must be >= 2")

    @property
    def digit_max(self) -> int:
        return self.base - 1

    @property
    def plane_count(self) -> int:
        return max(1, self.digit_max.bit_length())


@dataclass(frozen=True, slots=True)
class DigitTransducer:
    """Finite exact digit transducer.

    ``direction`` is ``"lsd"`` for least-significant-first scans (multiplication
    carries) and ``"msd"`` for most-significant-first scans (division
    remainders).  ``transition[(state,digit)] = (next_state, output_digit)``.
    """

    base: int
    states: tuple[int, ...]
    start_state: int
    transition: Mapping[tuple[int, int], tuple[int, int]]
    direction: str = "lsd"
    name: str = "digit_transducer"

    def __post_init__(self) -> None:
        if self.base < 2:
            raise ValueError(self.base)
        if self.direction not in ("lsd", "msd"):
            raise ValueError(self.direction)
        if self.start_state not in self.states:
            raise ValueError("start state absent")
        states = set(map(int, self.states))
        for q in states:
            for a in range(self.base):
                if (q, a) not in self.transition:
                    raise ValueError(("missing transition", q, a))
                nq, out = self.transition[q, a]
                if int(nq) not in states:
                    raise ValueError(("transition escapes state set", q, a, nq))
                if not 0 <= int(out) < self.base:
                    raise ValueError(("output digit", out))

    def step(self, state: int, digit: int) -> tuple[int, int]:
        next_state, output = self.transition[int(state), int(digit)]
        return int(next_state), int(output)

    @property
    def state_index(self) -> dict[int, int]:
        return {q: i for i, q in enumerate(self.states)}

    def digit_functions(self) -> tuple[tuple[int, ...], ...]:
        idx = self.state_index
        return tuple(
            tuple(idx[int(self.transition[q, a][0])] for q in self.states)
            for a in range(self.base)
        )


@dataclass(frozen=True, slots=True)
class FunctionMonoid:
    """Transition monoid generated by a finite digit transducer."""

    functions: tuple[tuple[int, ...], ...]
    identity: int
    digit_function: tuple[int, ...]
    composition: tuple[tuple[int, ...], ...]

    @property
    def size(self) -> int:
        return len(self.functions)


def canonicalize_digit_transducer(transducer: DigitTransducer) -> DigitTransducer:
    """Return a reachable, state-renaming-independent canonical machine.

    States are numbered by deterministic BFS from the start state using input
    digits in radix order.  Compiler caches therefore depend on the Mealy
    semantics reachable from the start, not caller-specific state labels.
    """
    mapping = {int(transducer.start_state): 0}
    order = [int(transducer.start_state)]
    cursor = 0
    while cursor < len(order):
        q = order[cursor]
        cursor += 1
        for digit in range(transducer.base):
            nq, _out = transducer.step(q, digit)
            if nq not in mapping:
                mapping[nq] = len(order)
                order.append(nq)
    transition = {}
    for old in order:
        q = mapping[old]
        for digit in range(transducer.base):
            nq, out = transducer.step(old, digit)
            transition[q, digit] = (mapping[nq], out)
    return DigitTransducer(
        transducer.base,
        tuple(range(len(order))),
        0,
        transition,
        transducer.direction,
        transducer.name,
    )


TransducerKey = tuple[int, str, tuple[tuple[tuple[int, int], ...], ...]]


def canonical_transducer_key(transducer: DigitTransducer) -> TransducerKey:
    t = canonicalize_digit_transducer(transducer)
    rows = tuple(
        tuple(t.transition[q, digit] for digit in range(t.base)) for q in t.states
    )
    return t.base, t.direction, rows


@lru_cache(maxsize=256)
def _monoid_from_canonical_key(key: TransducerKey, max_elements: int) -> FunctionMonoid:
    base, _direction, rows = key
    n = len(rows)
    identity_fn = tuple(range(n))
    generators = tuple(tuple(int(rows[q][a][0]) for q in range(n)) for a in range(base))
    funcs: list[tuple[int, ...]] = []
    ids: dict[tuple[int, ...], int] = {}

    def intern(f: tuple[int, ...]) -> int:
        old = ids.get(f)
        if old is not None:
            return old
        if len(funcs) >= max_elements:
            raise RuntimeError(f"transition monoid exceeds {max_elements} elements")
        i = len(funcs)
        ids[f] = i
        funcs.append(f)
        return i

    identity = intern(identity_fn)
    for g in generators:
        intern(g)
    cursor = 0
    while cursor < len(funcs):
        f = funcs[cursor]
        snapshot = tuple(funcs)
        for g in snapshot:
            intern(tuple(f[g[q]] for q in range(n)))
            intern(tuple(g[f[q]] for q in range(n)))
        cursor += 1
    comp = tuple(
        tuple(ids[tuple(after[before[q]] for q in range(n))] for before in funcs)
        for after in funcs
    )
    return FunctionMonoid(
        tuple(funcs), identity, tuple(ids[g] for g in generators), comp
    )


def synthesize_function_monoid(
    transducer: DigitTransducer, *, max_elements: int = 4096
) -> FunctionMonoid:
    """Exact transition monoid keyed by canonical reachable machine semantics."""
    return _monoid_from_canonical_key(
        canonical_transducer_key(transducer), int(max_elements)
    )


def digit_root_from_values(
    values: Sequence[int], arena: FormulaArena, spec: DigitSpec
) -> FormulaRoot:
    """Ingest an exact closed digit word, LSD first."""
    forbid_in_powered_jump("digit_root_from_values")
    vals = tuple(map(int, values))
    if not vals or any(not 0 <= v < spec.base for v in vals):
        raise ValueError("digit out of range")
    return FormulaRoot(literal_planes(vals, arena, spec.plane_count))


def digit_root_from_int(
    value: int, arena: FormulaArena, spec: DigitSpec
) -> FormulaRoot:
    forbid_in_powered_jump("digit_root_from_int")
    n = int(value)
    if n < 0:
        raise ValueError("nonnegative integers only")
    return digit_root_from_values(digits_lsd(n, spec.base), arena, spec)


def digit_value_masks(
    arena: FormulaArena, root: FormulaRoot, spec: DigitSpec
) -> tuple[Expr, ...]:
    if root.plane_count != spec.plane_count:
        raise ValueError((root.plane_count, spec.plane_count))
    key = ("digit-value-masks", spec.base, canonical_root_key(root))
    cached = arena.metadata_get(key)
    if isinstance(cached, tuple) and len(cached) == spec.base:
        return cached
    masks = tuple(
        arena.predicate("EQ", digit, root.planes) for digit in range(spec.base)
    )
    arena.metadata_set(key, masks)
    return masks


def digit_root_from_value_masks(
    arena: FormulaArena,
    value_masks: Sequence[Expr],
    spec: DigitSpec,
) -> FormulaRoot:
    """Encode one-hot exact digit masks into the canonical bit-plane root."""
    masks = tuple(value_masks)
    if len(masks) != spec.base:
        raise ValueError((len(masks), spec.base))
    width = masks[0].width if masks else 0
    if any(mask.width != width for mask in masks):
        raise ValueError("width mismatch")
    return FormulaRoot(
        tuple(
            arena.or_many((masks[d] for d in range(spec.base) if (d >> bit) & 1), width)
            for bit in range(spec.plane_count)
        )
    )


def _processing_root(
    arena: FormulaArena, root: FormulaRoot, direction: str
) -> FormulaRoot:
    if direction == "lsd":
        return root
    return FormulaRoot(tuple(arena.mirror(p) for p in root.planes))


@dataclass(frozen=True, slots=True)
class CompiledDigitTransduction:
    output: FormulaRoot
    incoming_state_masks: tuple[Expr, ...]
    outgoing_state_masks: tuple[Expr, ...]
    monoid: FunctionMonoid
    transducer: DigitTransducer
    prefix_projection: FormulaPrefixMonoidProjection

    def incoming_state_at(self, arena: FormulaArena, position: int) -> int:
        position = int(position)
        if not 0 <= position < self.output.width:
            raise IndexError(position)
        hits = [
            int(q)
            for q, mask in zip(self.transducer.states, self.incoming_state_masks)
            if arena.eval_closed_bit(mask, position)
        ]
        if len(hits) != 1:
            raise AssertionError((position, hits))
        return hits[0]

    def outgoing_state_at(self, arena: FormulaArena, position: int) -> int:
        position = int(position)
        if not 0 <= position < self.output.width:
            raise IndexError(position)
        hits = [
            int(q)
            for q, mask in zip(self.transducer.states, self.outgoing_state_masks)
            if arena.eval_closed_bit(mask, position)
        ]
        if len(hits) != 1:
            raise AssertionError((position, hits))
        return hits[0]

    def output_digit_at(self, arena: FormulaArena, position: int) -> int:
        return closed_digit_at(arena, self.output, int(position))

    def final_state(self, arena: FormulaArena) -> int:
        pos = self.output.width - 1 if self.transducer.direction == "lsd" else 0
        hits = [
            q
            for q, mask in zip(self.transducer.states, self.outgoing_state_masks)
            if arena.eval_closed_bit(mask, pos)
        ]
        if len(hits) != 1:
            raise AssertionError(("non-deterministic final state", hits))
        return int(hits[0])


def compile_digit_transducer(
    arena: FormulaArena,
    root: FormulaRoot,
    spec: DigitSpec,
    transducer: DigitTransducer,
    *,
    monoid: FunctionMonoid | None = None,
) -> CompiledDigitTransduction:
    """Compile exact output digit formulas using an associative monoid scan."""
    if transducer.base != spec.base:
        raise ValueError((transducer.base, spec.base))
    transducer = canonicalize_digit_transducer(transducer)
    expected_monoid = synthesize_function_monoid(transducer)
    if monoid is not None and monoid != expected_monoid:
        raise ValueError("monoid does not match canonical transducer")
    monoid = expected_monoid
    cache_key = (
        "digit-transduction",
        canonical_root_key(root),
        spec.base,
        canonical_transducer_key(transducer),
    )
    cached = arena.metadata_get(cache_key)
    if isinstance(cached, CompiledDigitTransduction):
        return cached
    proc = _processing_root(arena, root, transducer.direction)
    masks = digit_value_masks(arena, proc, spec)
    prefix_projection = compile_formula_prefix_monoid(
        arena,
        tuple(
            arena.or_many(
                (
                    mask
                    for digit, mask in enumerate(masks)
                    if monoid.digit_function[digit] == element
                ),
                proc.width,
            )
            for element in range(monoid.size)
        ),
        FiniteMonoid(monoid.composition, monoid.identity),
    )
    summaries = prefix_projection.masks

    state_idx = transducer.state_index
    outgoing_groups: list[list[Expr]] = [[] for _ in transducer.states]
    start_idx = state_idx[transducer.start_state]
    for mid, fn in enumerate(monoid.functions):
        outgoing_groups[fn[start_idx]].append(summaries[mid])
    outgoing = tuple(arena.or_many(items, proc.width) for items in outgoing_groups)

    incoming_list: list[Expr] = []
    first = arena.range_mask(0, 1, proc.width)
    for qi, mask in enumerate(outgoing):
        shifted = arena.shl(mask, 1)
        if qi == start_idx:
            shifted = arena.or_(shifted, first)
        incoming_list.append(shifted)
    incoming = tuple(incoming_list)

    output_masks: list[list[Expr]] = [[] for _ in range(spec.base)]
    for qi, q in enumerate(transducer.states):
        for digit in range(spec.base):
            _nq, out = transducer.step(q, digit)
            output_masks[out].append(arena.and_(incoming[qi], masks[digit]))
    value_masks = tuple(arena.or_many(items, proc.width) for items in output_masks)

    output = digit_root_from_value_masks(arena, value_masks, spec)
    if transducer.direction == "msd":
        output = FormulaRoot(tuple(arena.mirror(p) for p in output.planes))
        incoming = tuple(arena.mirror(p) for p in incoming)
        outgoing = tuple(arena.mirror(p) for p in outgoing)
    compiled = CompiledDigitTransduction(
        output,
        incoming,
        outgoing,
        monoid,
        transducer,
        prefix_projection,
    )
    arena.metadata_set(cache_key, compiled)
    return compiled


def crop_root(arena: FormulaArena, root: FormulaRoot, width: int) -> FormulaRoot:
    return FormulaRoot(tuple(arena.crop(p, int(width)) for p in root.planes))


def closed_digit_at(arena: FormulaArena, root: FormulaRoot, position: int) -> int:
    i = int(position)
    return sum(arena.eval_closed_bit(p, i) << b for b, p in enumerate(root.planes))


def trim_closed_root(arena: FormulaArena, root: FormulaRoot) -> FormulaRoot:
    """Drop high zero digits from a closed root without materializing the word."""
    top = root.width - 1
    while top > 0 and closed_digit_at(arena, root, top) == 0:
        top -= 1
    return crop_root(arena, root, top + 1) if top + 1 != root.width else root


def synthesize_multiply_add(
    base: int, multiplier: int, addend: int = 0
) -> DigitTransducer:
    """Synthesize the exact LSD-first monoid for ``x -> multiplier*x + addend``."""
    b, m, c0 = int(base), int(multiplier), int(addend)
    if b < 2 or m < 0 or c0 < 0:
        raise ValueError((base, multiplier, addend))
    # Reachable carry closure under every input digit.
    states = {c0}
    todo = [c0]
    while todo:
        c = todo.pop()
        for a in range(b):
            nc = (m * a + c) // b
            if nc not in states:
                states.add(nc)
                todo.append(nc)
    st = tuple(sorted(states))
    trans = {}
    for c in st:
        for a in range(b):
            z = m * a + c
            trans[c, a] = (z // b, z % b)
    return DigitTransducer(b, st, c0, trans, "lsd", f"mul{m}_add{c0}")


def synthesize_divide(base: int, divisor: int) -> DigitTransducer:
    """Synthesize the exact MSD-first long-division remainder monoid."""
    b, d = int(base), int(divisor)
    if b < 2 or d <= 0:
        raise ValueError((base, divisor))
    states = tuple(range(d))
    trans = {}
    for r in states:
        for a in range(b):
            z = r * b + a
            trans[r, a] = (z % d, z // d)
    return DigitTransducer(b, states, 0, trans, "msd", f"divide_{d}")


def _flush_padding(base: int, states: Sequence[int]) -> int:
    m = max(map(int, states), default=0)
    if m <= 0:
        return 1
    # Enough zero digits to drain the largest carry under repeated // base.
    n = 0
    while m:
        m //= int(base)
        n += 1
    return max(1, n)


def multiply_add_formula(
    arena: FormulaArena,
    root: FormulaRoot,
    spec: DigitSpec,
    multiplier: int,
    addend: int = 0,
) -> tuple[FormulaRoot, CompiledDigitTransduction]:
    """Exact closed formula for ``multiplier*x + addend``."""
    trans = synthesize_multiply_add(spec.base, multiplier, addend)
    pad = _flush_padding(spec.base, trans.states)
    padded = FormulaRoot(tuple(arena.resize(p, root.width + pad) for p in root.planes))
    compiled = compile_digit_transducer(arena, padded, spec, trans)
    out = trim_closed_root(arena, compiled.output)
    return out, CompiledDigitTransduction(
        out,
        tuple(arena.crop(x, out.width) for x in compiled.incoming_state_masks),
        tuple(arena.crop(x, out.width) for x in compiled.outgoing_state_masks),
        compiled.monoid,
        compiled.transducer,
        compiled.prefix_projection,
    )


def divide_formula(
    arena: FormulaArena,
    root: FormulaRoot,
    spec: DigitSpec,
    divisor: int,
    *,
    require_exact: bool = True,
) -> tuple[FormulaRoot, CompiledDigitTransduction]:
    """Exact closed formula for integer long division by ``divisor``."""
    trans = synthesize_divide(spec.base, divisor)
    compiled = compile_digit_transducer(arena, root, spec, trans)
    if require_exact and compiled.final_state(arena) != 0:
        raise ValueError("division is not exact")
    out = trim_closed_root(arena, compiled.output)
    return out, CompiledDigitTransduction(
        out,
        tuple(arena.crop(x, out.width) for x in compiled.incoming_state_masks),
        tuple(arena.crop(x, out.width) for x in compiled.outgoing_state_masks),
        compiled.monoid,
        compiled.transducer,
        compiled.prefix_projection,
    )


def root_to_int(arena: FormulaArena, root: FormulaRoot, spec: DigitSpec) -> int:
    forbid_in_powered_jump("digit_root_to_int")
    n = 0
    for i in range(root.width - 1, -1, -1):
        n = n * spec.base + closed_digit_at(arena, root, i)
    return n


