"""Lazy source-bound decimal diagonal carries for Antihydra.

The raw multiplication field ``15**n H`` and the physical field
``15**n H - 5**n K = 10**n H_n`` are projected from one authenticated x15
morphism.  Requested columns are generated by the bounded spatial recurrence

``c_a(j + 1) = floor((a d_j + c_a(j)) / 10)``.

No temporal history is retained, and ordinary term queries never enter this
module.  Complete-width requests must supply both an output-cell limit and an
active scratch reservation hook.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from fractions import Fraction
from math import lcm
from typing import TYPE_CHECKING, Final

from number_compiler.arithmetic.contracts.block_effect import (
    BlockContextBudgetExceeded,
)
from number_compiler.arithmetic.fields.radix import iter_digits_lsd
from number_compiler.resources.metric_keys import antihydra as _keys

if TYPE_CHECKING:
    from number_compiler.sequences.antihydra.mahler_x15_source_morphism import (
        X15CarryMorphism,
    )


DEFAULT_DIAGONAL_MODULI: Final[tuple[int, ...]] = (
    99,
    100,
    101,
    198,
    999,
    1001,
    9999,
)
MAX_DIAGONAL_COLUMNS: Final[int] = 8192
DIAGONAL_LANE_LAYOUT: Final[tuple[tuple[str, int, int], ...]] = (
    ("raw_digit", 0, 4),
    ("physical_digit", 4, 4),
    ("raw_next_digit", 8, 4),
    ("physical_next_digit", 12, 4),
    ("physical_floor_digit_correction", 16, 3),
    ("raw_carry_15", 19, 4),
    ("physical_carry_15", 23, 4),
    ("raw_borrow_225_15", 27, 1),
    ("physical_borrow_225_15", 28, 1),
    ("raw_borrow_15_1", 29, 1),
    ("raw_digit_decrease", 30, 1),
)


@dataclass(frozen=True, slots=True)
class DiagonalProjectionResidue:
    modulus: int
    raw_carry: int
    raw_borrow_225_15: int
    raw_borrow_15_1: int
    physical_carry: int
    physical_borrow_225_15: int


@dataclass(frozen=True, slots=True)
class DiagonalCarryVectors:
    """All columns in 32-bit slots of one JSON-hex-friendly integer."""

    packed_word: int
    columns: int
    column_stride_bits: int = 32
    lane_layout: tuple[tuple[str, int, int], ...] = DIAGONAL_LANE_LAYOUT

    def lane_value(self, column: int, lane: str) -> int:
        if type(column) is not int or not 0 <= column < self.columns:
            raise IndexError("diagonal column is outside the packed field")
        for name, shift, width in self.lane_layout:
            if name == lane:
                return (
                    self.packed_word >> (self.column_stride_bits * column + shift)
                ) & ((1 << width) - 1)
        raise KeyError(lane)


@dataclass(frozen=True, slots=True)
class DiagonalCarryField:
    ticks: int
    source_h: int
    endpoint_h: int
    floor_correction_k: int
    weighted_centered_innovation_j: int
    dyadic_guard_residue: int
    dyadic_guard_modulus_bits: int
    spatial_columns: int
    raw_cut_clock_15_mod_1000: int
    mod101_multiplier_phase: int
    mod101_floor_correction: int
    physical_endpoint_mod101: int
    laurent_coefficient_origin: int
    projection_moduli: tuple[DiagonalProjectionResidue, ...]
    common_crt_modulus: int
    vectors: DiagonalCarryVectors
    cut_j_start: int = 1
    vector_direction: str = "increasing decimal cut j"
    source_rooted: bool = True
    temporal_intermediate_rows: int = 0

    @property
    def offset_s_start(self) -> int:
        return 1 - self.ticks


@dataclass(frozen=True, slots=True, init=False)
class DiagonalCarryTower:
    """Authority-preserving lazy projection of one x15 carry morphism."""

    action: X15CarryMorphism
    _snapshot: tuple[object, ...]

    @classmethod
    def from_morphism(cls, action: X15CarryMorphism) -> DiagonalCarryTower:
        from number_compiler.sequences.antihydra.mahler_x15_source_morphism import (
            X15CarryMorphism,
        )

        if type(action) is not X15CarryMorphism:
            raise TypeError("diagonal carry requires an authenticated x15 morphism")
        action.require_issued()
        value = object.__new__(cls)
        object.__setattr__(value, "action", action)
        object.__setattr__(value, "_snapshot", (action,))
        value.require_issued()
        return value

    def require_issued(self) -> None:
        self.action.require_issued()
        if self._snapshot != (self.action,):
            raise ValueError("diagonal carry projection was altered")

    @property
    def ticks(self) -> int:
        self.require_issued()
        return self.action.ticks

    @property
    def source(self) -> int:
        self.require_issued()
        return self.action.integer_source

    @property
    def endpoint(self) -> int:
        self.require_issued()
        return self.action.integer_endpoint

    @property
    def correction(self) -> int:
        self.require_issued()
        return self.action.floor_correction

    def full_width(
        self,
        *,
        max_columns: int,
        max_observer_terms: int,
        reserve_bits: Callable[[int], None],
    ) -> int:
        """Demand the exact significant width, refusing before field allocation."""
        self.require_issued()
        _validate_limits(max_columns, max_observer_terms, reserve_bits)
        action = self.action
        return _full_width(
            action.ticks,
            action.source + 1,
            max_columns=max_columns,
            max_observer_terms=max_observer_terms,
            reserve_bits=reserve_bits,
        )

    def phase(
        self,
        signed_offset: int,
        *,
        physical: bool = False,
        max_columns: int,
        reserve_bits: Callable[[int], None],
    ) -> Fraction:
        """Demand one raw or physical Laurent phase from the same source."""
        self.require_issued()
        if type(signed_offset) is not int:
            raise TypeError("diagonal offset must be an integer")
        if type(physical) is not bool:
            raise TypeError("physical phase selector must be Boolean")
        if type(max_columns) is not int or not 1 <= max_columns <= MAX_DIAGONAL_COLUMNS:
            raise ValueError("diagonal phase limit is outside its hard bound")
        if not callable(reserve_bits):
            raise TypeError("diagonal phase requires scratch reservation")
        action = self.action
        ticks = action.ticks
        source = action.source + 1
        correction = action.floor_correction
        cut = ticks + signed_offset
        if cut <= 0:
            return Fraction(0)
        if cut > max_columns:
            raise BlockContextBudgetExceeded("diagonal phase exceeds output budget")
        scratch_bits = 32 * (cut + ticks.bit_length() + 64)
        reserve_bits(scratch_bits)
        action.charge_projection_metrics(
            (
                (_keys.ANTIHYDRA_ARITHMETIC_DIAGONAL_REQUESTS, 1),
                (_keys.ANTIHYDRA_ARITHMETIC_DIAGONAL_CELLS, 1),
                (
                    _keys.ANTIHYDRA_ARITHMETIC_DIAGONAL_OPERAND_BITS,
                    scratch_bits,
                ),
            )
        )
        denominator: int = 10**cut
        raw_multiplier: int = pow(15, ticks, denominator)
        raw: int = raw_multiplier * (source % denominator)
        raw %= denominator
        if physical:
            correction_multiplier: int = pow(5, ticks, denominator)
            raw -= correction_multiplier * (correction % denominator) % denominator
            raw %= denominator
        return Fraction(raw, denominator)

    def packed_field(
        self,
        columns: int = 0,
        *,
        max_columns: int,
        max_observer_terms: int,
        reserve_bits: Callable[[int], None],
        moduli: tuple[int, ...] = DEFAULT_DIAGONAL_MODULI,
    ) -> DiagonalCarryField:
        """Emit demanded columns from one powered top seam.

        ``columns=0`` means the complete significant field.  Both the exact
        complete width and an explicit positive width are checked against the
        two caller-provided limits before top-seam powers, vectors, or
        projection maps are allocated. Exact full-width discovery has its own
        prior reservation for the one raw power needed to count digits.
        """
        self.require_issued()
        action = self.action
        ticks = action.ticks
        source = action.source + 1
        endpoint = action.endpoint + 1
        correction = action.floor_correction
        if type(columns) is not int or columns < 0:
            raise ValueError("diagonal width must be nonnegative")
        _validate_limits(max_columns, max_observer_terms, reserve_bits)
        if (
            type(moduli) is not tuple
            or any(type(modulus) is not int or modulus < 2 for modulus in moduli)
            or len(set(moduli)) != len(moduli)
            or any(modulus not in DEFAULT_DIAGONAL_MODULI for modulus in moduli)
        ):
            raise ValueError("diagonal moduli must be a unique approved subset")
        if columns == 0:
            columns = _full_width(
                ticks,
                source,
                max_columns=max_columns,
                max_observer_terms=max_observer_terms,
                reserve_bits=reserve_bits,
            )
        elif columns > max_columns or columns > max_observer_terms:
            raise BlockContextBudgetExceeded(
                "diagonal field exceeds its observer budget"
            )
        if columns > MAX_DIAGONAL_COLUMNS:
            raise BlockContextBudgetExceeded("diagonal field exceeds hard limit")
        top_bits = 4 * (columns + 1) + 1
        operand_bits = 48 * (
            top_bits
            + ticks.bit_length()
            + source.bit_length()
            + correction.bit_length()
            + len(moduli) * max(1, columns)
            + 64
        )
        # Three byte digit tapes, a four-byte column buffer, the final packed
        # integer, modular-power outputs, and projection accumulators coexist.
        # Arithmetic work is reported separately from this live-storage bound.
        live_bits = 56 * columns + 6 * top_bits + 32_768
        reserve_bits(live_bits)
        action.charge_projection_metrics(
            (
                (_keys.ANTIHYDRA_ARITHMETIC_DIAGONAL_REQUESTS, 1),
                (
                    _keys.ANTIHYDRA_ARITHMETIC_DIAGONAL_OPERAND_BITS,
                    operand_bits,
                ),
            )
        )
        top, raw, physical = _seam(
            columns,
            ticks=ticks,
            source=source,
            endpoint=endpoint,
            correction=correction,
        )
        raw_digits = _digits(raw, columns + 1)
        physical_digits = _digits(physical, columns + 1)
        parity = endpoint & 1
        floor_position = ticks
        ten_phase: int = pow(10, ticks, top)
        next_physical = (15 * physical - 5 * parity * ten_phase) % top
        expected_next_phase: int = pow(10, ticks + 1, top)
        expected_next = expected_next_phase * ((3 * endpoint) // 2) % top
        if next_physical != expected_next:
            raise ArithmeticError("physical next-step decimal seam was lost")
        next_physical_digits = _digits(next_physical, columns + 1)
        packed_columns = bytearray(4 * columns)
        projection_values = {modulus: [0, 0, 0, 0, 0] for modulus in moduli}
        projection_weights = {modulus: 1 for modulus in moduli}
        cr15 = cr14 = cr210 = cr225 = 0
        cp15 = cp210 = cp225 = 0
        for index in range(columns):
            raw_digit = raw_digits[index]
            physical_digit = physical_digits[index]
            previous_cr15, previous_cp15 = cr15, cp15
            raw_next = (15 * raw_digit + cr15) % 10
            physical_unrounded_next = (15 * physical_digit + cp15) % 10
            local_floor = 5 * parity if index == floor_position else 0
            physical_next = physical_unrounded_next - local_floor
            if physical_next != next_physical_digits[index]:
                raise ArithmeticError("physical diagonal digit lost floor correction")
            cr15 = (15 * raw_digit + cr15) // 10
            cr14 = (14 * raw_digit + cr14) // 10
            cr210 = (210 * raw_digit + cr210) // 10
            cr225 = (225 * raw_digit + cr225) // 10
            cp15 = (15 * physical_digit + cp15) // 10
            cp210 = (210 * physical_digit + cp210) // 10
            cp225 = (225 * physical_digit + cp225) // 10
            raw_borrow = cr225 - cr210 - cr15
            physical_borrow = cp225 - cp210 - cp15
            raw_borrow_15 = cr15 - cr14
            if (
                raw_next != 15 * raw_digit + previous_cr15 - 10 * cr15
                or physical_unrounded_next
                != 15 * physical_digit + previous_cp15 - 10 * cp15
            ):
                raise ArithmeticError("diagonal multiplication seam was lost")
            if not (
                0 <= cr15 < 15
                and 0 <= cp15 < 15
                and raw_borrow in (0, 1)
                and physical_borrow in (0, 1)
                and raw_borrow_15 in (0, 1)
            ):
                raise ArithmeticError("diagonal carry escaped its finite domain")
            next_raw_digit = raw_digits[index + 1]
            next_raw_output = (15 * next_raw_digit + cr15) % 10
            packed = (
                raw_digit
                | (physical_digit << 4)
                | (raw_next << 8)
                | (physical_next << 12)
                | (local_floor << 16)
                | (cr15 << 19)
                | (cp15 << 23)
                | (raw_borrow << 27)
                | (physical_borrow << 28)
                | (raw_borrow_15 << 29)
                | (int(next_raw_digit > next_raw_output) << 30)
            )
            start = 4 * index
            packed_columns[start : start + 4] = packed.to_bytes(4, "little")
            for modulus in moduli:
                weight = projection_weights[modulus]
                projected = projection_values[modulus]
                projected[0] = (projected[0] + weight * cr15) % modulus
                projected[1] = (projected[1] + weight * raw_borrow) % modulus
                projected[2] = (projected[2] + weight * raw_borrow_15) % modulus
                projected[3] = (projected[3] + weight * cp15) % modulus
                projected[4] = (projected[4] + weight * physical_borrow) % modulus
                projection_weights[modulus] = weight * 10 % modulus
        clock_gain: int = pow(52, ticks, 101)
        clock_correction_phase: int = pow(51, ticks, 101)
        clock_correction = (-clock_correction_phase * correction) % 101
        if (clock_gain * source + clock_correction) % 101 != endpoint % 101:
            raise ArithmeticError("diagonal mod-101 clock lost its source")
        action.charge_projection_metrics(
            ((_keys.ANTIHYDRA_ARITHMETIC_DIAGONAL_CELLS, columns),)
        )
        # Decoded tapes and top-seam integers need not coexist with the final
        # conversion of the four-byte column buffer to one retained integer.
        del (
            expected_next,
            next_physical,
            next_physical_digits,
            physical,
            physical_digits,
            raw,
            raw_digits,
            ten_phase,
            top,
        )
        vectors = DiagonalCarryVectors(
            int.from_bytes(packed_columns, "little"), columns
        )
        projections = tuple(
            DiagonalProjectionResidue(
                modulus,
                projection_values[modulus][0],
                projection_values[modulus][1],
                projection_values[modulus][2],
                projection_values[modulus][3],
                projection_values[modulus][4],
            )
            for modulus in moduli
        )
        raw_cut_clock: int = pow(15, ticks, 1000)
        return DiagonalCarryField(
            ticks,
            source,
            endpoint,
            correction,
            action.innovation,
            action.source & (action.denominator - 1),
            ticks,
            columns,
            raw_cut_clock,
            clock_gain,
            clock_correction,
            endpoint % 101,
            1 - ticks,
            projections,
            lcm(*moduli) if moduli else 1,
            vectors,
        )


def _full_width(
    ticks: int,
    source: int,
    *,
    max_columns: int,
    max_observer_terms: int,
    reserve_bits: Callable[[int], None],
) -> int:
    # The raw power is needed only to resolve the exact power-of-ten seam.
    # Reserve its conservative live-operand bound before materialization.
    reserve_bits(8 * ticks + 4 * source.bit_length() + 256)
    raw = 15**ticks * source
    width = _decimal_length(225 * raw) + 1
    if width > max_columns or width > max_observer_terms:
        raise BlockContextBudgetExceeded(
            "complete diagonal field exceeds its observer budget"
        )
    return width


def _seam(
    columns: int,
    *,
    ticks: int,
    source: int,
    endpoint: int,
    correction: int,
) -> tuple[int, int, int]:
    top: int = 10 ** (columns + 1)
    raw_multiplier: int = pow(15, ticks, top)
    correction_multiplier: int = pow(5, ticks, top)
    endpoint_multiplier: int = pow(10, ticks, top)
    raw: int = raw_multiplier * (source % top) % top
    physical: int = (raw - correction_multiplier * (correction % top)) % top
    expected: int = endpoint_multiplier * (endpoint % top) % top
    if physical != expected:
        raise ArithmeticError("diagonal raw/physical seam was lost")
    return top, raw, physical


def _validate_limits(
    max_columns: int,
    max_observer_terms: int,
    reserve_bits: Callable[[int], None],
) -> None:
    if (
        type(max_columns) is not int
        or not 1 <= max_columns <= MAX_DIAGONAL_COLUMNS
        or type(max_observer_terms) is not int
        or max_observer_terms < 1
    ):
        raise ValueError("diagonal observer limits must be positive and bounded")
    if not callable(reserve_bits):
        raise TypeError("diagonal observer requires scratch reservation")


def _decimal_length(value: int) -> int:
    if value < 1:
        return 1
    estimate = 1 + (value.bit_length() * 30103) // 100000
    base = 10 ** max(0, estimate - 1)
    while value < base:
        base //= 10
        estimate -= 1
    while value >= 10 * base:
        base *= 10
        estimate += 1
    return estimate


def _digits(value: int, width: int) -> bytearray:
    digits = bytearray(iter_digits_lsd(value, 10))
    if len(digits) > width:
        raise ArithmeticError("diagonal seam exceeds its top modulus")
    digits.extend([0] * (width - len(digits)))
    return digits


