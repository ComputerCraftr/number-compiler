"""Exact fixed-width 2^q 11^g digit and carry quotient.

A spatial BCD bit plane is an integer with one bit per decimal column.  The
one-step multiplication-by-2 and multiplication-by-11 transducers use Boolean
AND, OR, XOR, and NAND operations on *whole planes*.  For 11, the carry is a
2x2 Boolean affine matrix (generate, propagate), whose two-child composition
can be evaluated as a word-parallel prefix tower.  No intermediate multiplier
rows or skew-matrix squares are materialized.

The temporal quotient is a 2-adic carry phase joined with the 5-adic log_16
coordinate of 2^q 11^g.  Its cross-precision children share the entire lower
suffix, so continuant children can be generated by ordered upper shears.

IMPORTANT: this is a certified HOMOGENEOUS multiplication stage.  Reverse/add
has a separate width-skewed additive forcing.  Neither this module nor its
Q19 bridge asserts an all-depth reverse/add temporal period.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import TYPE_CHECKING

from .q19_broadword_publisher import bcd_digit_at

if TYPE_CHECKING:
    from .q19_authenticated_carry_phase import AuthenticatedFiveCarryWindow
    from .q19_repeat_port import Q19RepeatAction


def _is_tuple(value: object) -> bool:
    return isinstance(value, tuple)


def _natural(x: int, name: str) -> None:
    if type(x) is not int or x < 0:
        raise ValueError(f"{name} must be a nonnegative integer")


def _positive(x: int, name: str) -> None:
    if type(x) is not int or x <= 0:
        raise ValueError(f"{name} must be a positive integer")


def _bmask(width: int) -> int:
    return (1 << width) - 1


def nand(a: int, b: int, width: int) -> int:
    """Boolean NAND on the finite spatial band, never Python's infinite ~."""
    return (~(a & b)) & _bmask(width)


def _add_five_bits(
    aa: tuple[int, ...], bb: tuple[int, ...], width: int
) -> tuple[int, int, int, int, int]:
    """Five-bit parallel addition, modulo 32 in every spatial column."""
    mask = _bmask(width)
    carry = 0
    result: list[int] = []
    for bit in range(5):
        a = aa[bit] if bit < len(aa) else 0
        b = bb[bit] if bit < len(bb) else 0
        a &= mask
        b &= mask
        p = a ^ b
        result.append((p ^ carry) & mask)
        carry = ((a & b) | (p & carry)) & mask
    return result[0], result[1], result[2], result[3], result[4]


def _carry_prefix(
    generate: int, propagate: int, width: int, initial_carry: int = 0
) -> int:
    """Parallel two-child affine carry composition.

    A leaf has c_out = g OR (p AND c_in).  The composition of left
    (gL,pL) then right (gR,pR) is
        (gR OR (pR AND gL), pR AND pL).
    Each doubling combines two adjacent blocks.  Outputs are all c_out
    values for c_before_column_zero = 0 in O(log width) broadword stages.
    """
    if type(initial_carry) is not int or initial_carry not in (0, 1):
        raise ValueError("incoming Boolean carry must be 0 or 1")
    mask = _bmask(width)
    g, p = generate & mask, propagate & mask
    shift = 1
    while shift < width:
        shifted_g = (g << shift) & mask
        # NAND(NAND(g,g), NAND(p,shifted_g)) == g OR (p & shifted_g).
        g = nand(nand(g, g, width), nand(p, shifted_g, width), width)
        # Columns below `shift` have no left sibling: preserve their P.
        # Without this boundary identity, incoming carry=1 is lost.
        p &= ((p << shift) | ((1 << shift) - 1)) & mask
        shift <<= 1
    return g | (p if initial_carry else 0)


def _carry_linear_two_child_tower(
    generate: int, propagate: int, width: int, initial_carry: int = 0
) -> int:
    """Independent O(width) two-child Boolean-affine matrix tower.

    A node represents the ordered composition of its two children as
    (generate, propagate).  This builds at most 2*next_power_of_two(width)
    nodes and projects every leaf carry with one downward traversal; no
    repeated temporal squarings, no source DAG walks, and no width history.
    """
    _positive(width, "carry tower width")
    if type(initial_carry) is not int or initial_carry not in (0, 1):
        raise ValueError("incoming Boolean carry must be 0 or 1")
    n = 1 << (width - 1).bit_length()
    generators = [0] * (2 * n)
    propagators = [1] * (2 * n)
    for j in range(width):
        generators[n + j] = (generate >> j) & 1
        propagators[n + j] = (propagate >> j) & 1
    for node in range(n - 1, 0, -1):
        left, right = node * 2, node * 2 + 1
        generators[node] = generators[right] | (propagators[right] & generators[left])
        propagators[node] = propagators[right] & propagators[left]
    result = 0
    stack = [(1, initial_carry)]
    while stack:
        node, inlet = stack.pop()
        if node >= n:
            j = node - n
            if j < width:
                result |= (generators[node] | (propagators[node] & inlet)) << j
        else:
            left, right = node * 2, node * 2 + 1
            midpoint = generators[left] | (propagators[left] & inlet)
            stack.append((right, midpoint))
            stack.append((left, inlet))
    return result


@dataclass(frozen=True, slots=True)
class BCDPlanes:
    """Fixed-width decimal low-end band, including possible leading zeroes."""

    width: int
    planes: tuple[int, int, int, int]

    def __post_init__(self) -> None:
        _positive(self.width, "BCD width")
        if not _is_tuple(self.planes) or len(self.planes) != 4:
            raise ValueError("four BCD bit planes are required")
        mask = _bmask(self.width)
        if any(type(x) is not int or x < 0 or x & ~mask for x in self.planes):
            raise ValueError("invalid BCD spatial plane")
        # Only illegal BCD values are 10..15, characterized by 8 AND (4 OR 2).
        _b0, b1, b2, b3 = self.planes
        if b3 & (b2 | b1):
            raise ValueError("BCD bit planes contain a decimal digit above 9")

    @classmethod
    def from_digits(cls, digits_lsd: tuple[int, ...]) -> BCDPlanes:
        if not _is_tuple(digits_lsd) or not digits_lsd:
            raise ValueError("nonempty fixed-width LSD-first digits required")
        masks = [0, 0, 0, 0]
        for i, d in enumerate(digits_lsd):
            if type(d) is not int or not 0 <= d <= 9:
                raise ValueError("invalid decimal digit")
            for bit in range(4):
                masks[bit] |= ((d >> bit) & 1) << i
        return cls(len(digits_lsd), (masks[0], masks[1], masks[2], masks[3]))

    @classmethod
    def from_residue(cls, residue: int, width: int) -> BCDPlanes:
        _natural(residue, "decimal residue")
        _positive(width, "decimal width")
        if residue >= 10**width:
            raise ValueError("residue exceeds requested decimal precision")
        digits: list[int] = []
        for _ in range(width):
            residue, d = divmod(residue, 10)
            digits.append(d)
        return cls.from_digits(tuple(digits))

    def digits_lsd(self) -> tuple[int, ...]:
        return tuple(bcd_digit_at(self.planes, j) for j in range(self.width))

    def residue(self) -> int:
        value = 0
        for j in range(self.width - 1, -1, -1):
            value = 10 * value + bcd_digit_at(self.planes, j)
        return value

    def restrict(self, width: int) -> BCDPlanes:
        _positive(width, "projection width")
        mask = _bmask(width)
        p0, p1, p2, p3 = self.planes
        return type(self)(width, (p0 & mask, p1 & mask, p2 & mask, p3 & mask))

    def trimmed_digits_lsd(self) -> tuple[int, ...]:
        p0, p1, p2, p3 = self.planes
        width = max(1, (p0 | p1 | p2 | p3).bit_length())
        return tuple(bcd_digit_at(self.planes, j) for j in range(width))

    def multiplier_two_carry_on(self) -> int:
        """Actual carry into the next decimal column when multiplying by 2."""
        b0, b1, b2, b3 = self.planes
        return (b3 | (b2 & (b1 | b0))) & _bmask(self.width)

    def two_five_complementary_sheets(self) -> tuple[int, tuple[int, int, int]]:
        """Lossless source split d = 5*q2 + r5, with r5 in 0..4.

        The binary carry sheet q2 is floor(d/5); the complementary 5-way
        remainder sheet r5 is computed by Boolean subtraction of 5*q2.
        This is exactly the 2rev10 two-generation carry decoder's local
        digit port, without constructing its successor or any decimal row.
        """
        q2 = self.multiplier_two_carry_on()
        rem = _add_five_bits(self.planes, (q2, q2, 0, q2, q2), self.width)
        if rem[3] or rem[4] or rem[2] & (rem[1] | rem[0]):
            raise AssertionError("Boolean two-sheet source remainder escaped base five")
        return q2, rem[:3]

    def multiply_two(self, initial_carry: int = 0) -> tuple[BCDPlanes, int]:
        """Produce 2*x + incoming port, without scanning decimal columns."""
        if type(initial_carry) is not int or initial_carry not in (0, 1):
            raise ValueError("incoming Boolean carry must be 0 or 1")
        width = self.width + 1
        forced = self.multiplier_two_carry_on()
        cin = ((forced << 1) | initial_carry) & _bmask(width)
        b0, b1, b2, b3 = self.planes
        raw = (cin, b0, b1, b2, b3)
        # Subtract 10 from each column with carry, using -10 == 22 mod32.
        out = _add_five_bits(raw, (0, forced, forced, 0, forced), width)
        return BCDPlanes(width, out[:4]), forced

    def multiply_eleven(
        self, initial_carry: int = 0, *, linear_tower: bool = False
    ) -> tuple[BCDPlanes, int]:
        """2-child carry matrices for x + (x << decimal 1).

        ``linear_tower=True`` uses an O(width)-node balanced carry matrix
        tower.  The default word-parallel scan uses O(log width) broadword
        stages and is substantially faster for Python arbitrary integers.
        Both are the same ordered Boolean affine composition.
        """
        if type(linear_tower) is not bool:
            raise TypeError("linear_tower must be a Boolean choice")
        if type(initial_carry) is not int or initial_carry not in (0, 1):
            raise ValueError("incoming Boolean carry must be 0 or 1")
        width = self.width + 2
        mask = _bmask(width)
        old = self.planes
        shifted = tuple((p << 1) & mask for p in old)
        # Sum of two decimal columns (0..18), *before* the incoming carry.
        raw = _add_five_bits(old, shifted, width)
        b0, b1, b2, b3, b4 = raw
        generate = (b4 | (b3 & (b2 | b1))) & mask  # raw >= 10
        propagate = b3 & b0 & ~(b4 | b2 | b1) & mask  # raw == 9
        carry = (
            _carry_linear_two_child_tower(generate, propagate, width, initial_carry)
            if linear_tower
            else _carry_prefix(generate, propagate, width, initial_carry)
        )
        cin = ((carry << 1) | initial_carry) & mask
        with_in = _add_five_bits(raw, (cin,), width)
        # Each output digit = raw + cin - 10*carry, in Boolean ring.
        result = _add_five_bits(with_in, (0, carry, carry, 0, carry), width)
        return BCDPlanes(width, result[:4]), carry


def log_16_of_11_mod_5_power(width: int) -> int:
    """Construct eta with 16**eta == 11 (mod 5**width).

    Because v5(16-1)=v5(11-1)=1, the 5-adic logarithmic coordinate
    lifts by exactly one base-5 digit at each precision.
    """
    _positive(width, "5-adic precision")
    eta = 0
    power5 = 1
    for level in range(1, width):
        modulus = 5 ** (level + 1)
        target = 11 % modulus
        for digit in range(5):
            trial = eta + digit * power5
            if pow(16, trial, modulus) == target:
                eta = trial
                break
        else:
            raise AssertionError("5-adic 16-logarithm Hensel lift failed")
        power5 *= 5
    return eta


def _order_eleven_mod_two_power(exponent: int) -> int:
    if exponent <= 1:
        return 1
    return 2 if exponent == 2 else 1 << (exponent - 2)


@dataclass(frozen=True, slots=True)
class Mixed211Phase:
    """Exact right congruence of 2**q * 11**g at decimal depth k.

    q is capped at k for the 2-adic valuation, q4 retains the 5-adic
    Teichmueller phase, and t5 is q//4 + eta*g mod 5**(k-1).
    g2 is g mod ord_(2**(k-q_cap))(11), if unsaturated.
    """

    k: int
    q_cap: int
    q4: int
    g2: int
    t5: int

    def __post_init__(self) -> None:
        _positive(self.k, "decimal precision")
        modulus5 = 5 ** (self.k - 1)
        if (
            type(self.q_cap) is not int
            or not 0 <= self.q_cap <= self.k
            or type(self.q4) is not int
            or not 0 <= self.q4 < 4
            or (self.q_cap < self.k and self.q4 != self.q_cap % 4)
            or type(self.t5) is not int
            or not 0 <= self.t5 < modulus5
        ):
            raise ValueError("invalid mixed 2/5-adic 2^q11^g phase")
        order = _order_eleven_mod_two_power(self.k - self.q_cap)
        if type(self.g2) is not int or not 0 <= self.g2 < order:
            raise ValueError("invalid 2-adic eleven phase")

    @classmethod
    def from_exponents(cls, q: int, g: int, k: int) -> Mixed211Phase:
        _natural(q, "power of two")
        _natural(g, "power of eleven")
        _positive(k, "decimal precision")
        cap = min(q, k)
        order = _order_eleven_mod_two_power(k - cap)
        t = (q // 4 + log_16_of_11_mod_5_power(k) * g) % (5 ** (k - 1))
        return cls(k, cap, q % 4, g % order, t)

    def residue(self) -> int:
        """Exact CRT reconstruction without constructing 2**q or 11**g."""
        m2, m5 = 1 << self.k, int(5**self.k)
        if self.q_cap == self.k:
            r2 = 0
        else:
            r2 = (1 << self.q_cap) * pow(11, self.g2, 1 << (self.k - self.q_cap)) % m2
        r5 = pow(2, self.q4, m5) * pow(16, self.t5, m5) % m5
        return r2 + m2 * (((r5 - r2) * pow(m2, -1, m5)) % m5)

    def power(self, extra_twos: int = 0, extra_elevens: int = 0) -> Mixed211Phase:
        """O(log exponents) phase action; no chronological multiplier rows."""
        _natural(extra_twos, "extra powers of two")
        _natural(extra_elevens, "extra powers of eleven")
        cap = min(self.k, self.q_cap + extra_twos)
        order = _order_eleven_mod_two_power(self.k - cap)
        return type(self)(
            self.k,
            cap,
            (self.q4 + extra_twos) % 4,
            (self.g2 + extra_elevens) % order,
            (
                self.t5
                + (self.q4 + extra_twos) // 4
                + log_16_of_11_mod_5_power(self.k) * extra_elevens
            )
            % (5 ** (self.k - 1)),
        )

    def children(self) -> tuple[Mixed211Phase, ...]:
        """All mixed cross-depth children of this finite phase.

        The 5-adic phase has five children.  The independent dyadic
        eleven phase contributes one or two children.  For saturated
        valuations, a source-selected child may newly expose q==k.
        """
        k = self.k + 1
        q_caps = (
            (self.q_cap,)
            if self.q_cap < self.k
            else ((self.k, k) if self.q4 == self.k % 4 else (k,))
        )
        children: list[Mixed211Phase] = []
        for q_cap in q_caps:
            old_order = _order_eleven_mod_two_power(self.k - self.q_cap)
            new_order = _order_eleven_mod_two_power(k - q_cap)
            if new_order % old_order:
                raise AssertionError("2-adic quotient has a nonintegral fiber")
            for branch in range(new_order // old_order):
                new_g = self.g2 + old_order * branch
                for pentadic in range(5):
                    children.append(
                        type(self)(
                            k,
                            q_cap,
                            self.q4,
                            new_g,
                            self.t5 + pentadic * (5 ** (self.k - 1)),
                        )
                    )
        if len({c.residue() for c in children}) != len(children):
            raise AssertionError("mixed-adic child residues collided")
        if any(c.residue() % (10**self.k) != self.residue() for c in children):
            raise AssertionError("mixed-adic children do not project to parent")
        return tuple(children)

    def source_child(self, q: int, g: int) -> Mixed211Phase:
        """Refuse an unsupported child without an exact source exponent pair."""
        parent = type(self).from_exponents(q, g, self.k)
        if parent != self:
            raise ValueError("source exponent pair does not belong to parent phase")
        child = type(self).from_exponents(q, g, self.k + 1)
        if child not in self.children():
            raise AssertionError("source-selected mixed-adic child missing")
        return child

    def phase_period_after_saturation(self) -> int:
        """Temporal period for q and g increasing together after q>=k."""
        return 4 * (5 ** (self.k - 1))


Matrix2 = tuple[tuple[int, int], tuple[int, int]]


def _matmul(a: Matrix2, b: Matrix2) -> Matrix2:
    return (
        (a[0][0] * b[0][0] + a[0][1] * b[1][0], a[0][0] * b[0][1] + a[0][1] * b[1][1]),
        (a[1][0] * b[0][0] + a[1][1] * b[1][0], a[1][0] * b[0][1] + a[1][1] * b[1][1]),
    )


def ordered_child_matrices(
    phase: Mixed211Phase, lower_continuant: Matrix2
) -> tuple[tuple[Mixed211Phase, int, Matrix2], ...]:
    """One child matrix plus exact upper shears (no skew squaring).

    For a digit d and an ordered lower product B, X_d=M(d)B, where
      M(d)=[[d,1],[1,0]],  X_d=U(d-d0)X_d0,
      U(delta)=[[1,delta],[0,1]].
    No unequal continuant matrices are commuted.
    """
    if any(type(x) is not int for row in lower_continuant for x in row):
        raise ValueError("lower continuant must have exact integer entries")
    children = phase.children()
    scale = 10**phase.k
    candidates = tuple((child, child.residue() // scale) for child in children)
    d0 = candidates[0][1]
    x0 = _matmul(((d0, 1), (1, 0)), lower_continuant)
    return tuple(
        (child, d, _matmul(((1, d - d0), (0, 1)), x0)) for child, d in candidates
    )


@dataclass(frozen=True, slots=True)
class Powered211CarrySheets:
    """One direct powered source window and its actual Boolean carry sheets."""

    phase: Mixed211Phase
    source_modulo: int
    source: BCDPlanes
    next_two: BCDPlanes
    next_eleven: BCDPlanes
    carry_two: int
    carry_eleven: int
    # Cached on the exact immutable stage owner only. Never shared across
    # physical Q19 source occurrences or different mixed-adic phases.
    _q19_repeat_cache: tuple[tuple[int, ...], Q19RepeatAction] | None = field(
        default=None, init=False, repr=False, compare=False, hash=False
    )
    _q19_output_cache: tuple[int, ...] | None = field(
        default=None, init=False, repr=False, compare=False, hash=False
    )
    _authenticated_five_window: AuthenticatedFiveCarryWindow | None = field(
        default=None, init=False, repr=False, compare=False, hash=False
    )

    @classmethod
    def from_five_carry_sheet(
        cls,
        seed: int,
        twos: int,
        elevens: int,
        precision: int,
        carry_planes: tuple[int, int, int],
    ) -> Powered211CarrySheets:
        """Source-authenticated single-sheet inverse; no prior digit row.

        Carries are NOT sufficient alone on arbitrary input: the dyadic and
        5-adic congruences of the source phase must both validate the sheet.
        The default numerical source stage remains preferable when the
        original phase/digits are already available.
        """
        from .q19_authenticated_carry_phase import AuthenticatedFiveCarryWindow

        _natural(seed, "source multiplier input")
        phase = Mixed211Phase.from_exponents(twos, elevens, precision)
        window = AuthenticatedFiveCarryWindow.from_mixed211_source(
            seed, phase, carry_planes
        )
        source = BCDPlanes(precision, window.bcd_planes)
        two, carry_two = source.multiply_two()
        eleven, carry_eleven = source.multiply_eleven()
        stage = cls(
            phase,
            seed % (10**precision),
            source,
            two.restrict(precision),
            eleven.restrict(precision),
            carry_two,
            carry_eleven & _bmask(precision),
        )
        object.__setattr__(stage, "_authenticated_five_window", window)
        return stage

    @classmethod
    def _from_phase(
        cls, source_modulo: int, phase: Mixed211Phase
    ) -> Powered211CarrySheets:
        modulus = 10**phase.k
        residue = source_modulo * phase.residue() % modulus
        source = BCDPlanes.from_residue(residue, phase.k)
        two, carry_two = source.multiply_two()
        eleven, carry_eleven = source.multiply_eleven()
        return cls(
            phase,
            source_modulo,
            source,
            two.restrict(phase.k),
            eleven.restrict(phase.k),
            carry_two,
            carry_eleven & _bmask(phase.k),
        )

    @classmethod
    def from_seed(
        cls, seed: int, twos: int, elevens: int, precision: int
    ) -> Powered211CarrySheets:
        _natural(seed, "source multiplier input")
        phase = Mixed211Phase.from_exponents(twos, elevens, precision)
        return cls._from_phase(seed % (10**precision), phase)

    def power(self, extra_twos: int, extra_elevens: int) -> Powered211CarrySheets:
        """Reuse unchanged digit/carry sheets on exact temporal phase returns."""
        target = self.phase.power(extra_twos, extra_elevens)
        if target == self.phase:
            return self  # the lower digits and both outgoing carries are identical
        return type(self)._from_phase(self.source_modulo, target)

    def q19_next(self) -> tuple[int, ...]:
        """Consume the SAME bitplanes in the physical Q19 spatial producer.

        This is an exact ONE-STEP reverse/add of the powered source word,
        not a temporal powering theorem for ordinary reverse/add.
        """
        from .q19_broadword_publisher import PackedQ19

        if self._q19_output_cache is not None:
            return self._q19_output_cache
        repeat_cache = self._q19_repeat_cache
        if repeat_cache is not None:
            return repeat_cache[0]
        width = (
            self.source.planes[0]
            | self.source.planes[1]
            | self.source.planes[2]
            | self.source.planes[3]
        ).bit_length()
        if width == 0:
            return (0,)
        window = self._authenticated_five_window
        if window is not None:
            # A supplied ×5 sheet already recovered the source BCD planes.
            # Never reconstruct another complementary sheet just to consume
            # this same source in Q19.
            q19 = window.q19_repeat_state().frame
        else:
            q2, r5 = self.source.two_five_complementary_sheets()
            q19 = PackedQ19.from_two_five_carry_planes(q2, r5, width)
        _state, output = q19.advance(emit_digits=True)
        if output is None:
            raise AssertionError("Q19 physical source did not publish digits")
        object.__setattr__(self, "_q19_output_cache", output)
        return output

    def q19_next_with_repeats(self) -> tuple[tuple[int, ...], Q19RepeatAction]:
        """One physical Q19 step and carry-derived same-digit action masks.

        The repetition certificate is obtained from the SAME source-owned
        two/five carry planes as the successor, not a separately decoded row.
        Its validity is one transition only; no physical temporal cycle is
        assumed from the homogeneous multiplier phase.
        """
        from .q19_repeat_port import Q19RepeatPortState

        cached = self._q19_repeat_cache
        if cached is not None:
            return cached
        width = (
            self.source.planes[0]
            | self.source.planes[1]
            | self.source.planes[2]
            | self.source.planes[3]
        ).bit_length()
        if width == 0:
            raise ValueError("Q19 repeated-digit source must be positive")
        window = self._authenticated_five_window
        if window is not None:
            state = window.q19_repeat_state()
        else:
            c2, r5 = self.source.two_five_complementary_sheets()
            state = Q19RepeatPortState.from_two_five_carry_planes(c2, r5, width)
        _target, repeat, digits = state.advance(emit_digits=True)
        if digits is None:
            raise AssertionError("physical Q19 successor lost the requested digits")
        # The tuple is immutable and bound to this exact source phase. When
